CC = {}
for a, b in CONF: CC[(a, b)] = CC[(b, a)] = 0.35
def wed(a, b, cap=3.0):
    """Взвешенное расстояние правки: замена обычная 1, «похожая» 0.35, вставка/удаление 1, регистр 0.25."""
    n, m = len(a), len(b); prev = [j * 1.0 for j in range(m + 1)]
    for i in range(1, n + 1):
        cur = [i * 1.0] + [0.0] * m
        for j in range(1, m + 1):
            x, y = a[i - 1], b[j - 1]
            c = 0 if x == y else 0.25 if x.lower() == y.lower() else CC.get((x, y), CC.get((x.lower(), y.lower()), 1.0))
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + c)
        prev = cur
    return prev[m]
VOC = sorted(set(w for w in WORDS if len(w) >= 3), key=len)
def snap_word(w, maxd=1.0):
    """Заменяет слово ближайшим словарным, если расстояние ≤ maxd·(доля длины) и вариант единственный; регистр первой буквы сохраняется как у исходного."""
    if len(w) < 4 or any(ch.isdigit() for ch in w) or not all(ch.isalpha() or ch == '·' for ch in w): return w
    best = None; tie = False
    for v in VOC:
        if abs(len(v) - len(w)) > 1: continue
        d = wed(w.replace('·', '#'), v)
        if best is None or d < best[0] - 1e-9: best = (d, v); tie = False
        elif abs(d - best[0]) < 1e-9 and v != best[1]: tie = True
    if best and best[0] <= maxd * (0.34 if len(w) <= 6 else 0.28) * len(w) + 0.5 and best[0] > 0 and not tie:
        v = best[1]; return v
    return w
def snap_text(t):
    out = []
    for tok in t.split(' '):
        m = re.match(r'^([^\w·]*)([\w·]+)([^\w·]*)$', tok)
        out.append(m.group(1) + snap_word(m.group(2)) + m.group(3) if m else tok)
    return ' '.join(out)

def fix_code(t):
    """Шифр документа «77/113/114-Р-КЖ.И1-1.1»: слэш в шрифте не распознаётся (·), «КЖ» читается строчными."""
    t = re.sub(r'(?<=\d)·(?=\d)', '/', t)
    t = re.sub(r'\b(\d+/\d+/\d+)-([РP])-к[жХх]\b', lambda m: m.group(1) + '-Р-КЖ', t)
    return t
