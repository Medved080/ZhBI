    w("- Собственные тестовые записи ночи удалены/восстановлены (СМУ «QA-СМУ-Ночь…» создан и удалён — `smu_catalog` = 6; порог опоздания объекта 2 возвращён к 0). В журнале действий копии остались события этих проверок.")
    w("- Сервер `127.0.0.1:8041` (настоящий backend этой копии) и стенд `127.0.0.1:8051` оставлены запущенными; порты 8000/8020/8010 и старые стенды 8021/8031/8032/8033 не трогались.")
