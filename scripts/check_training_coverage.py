#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Страж покрытия учебного материала (2026-08-14).

Раздел «Обучение» собирает инструкцию из блоков, написанных НА РАЗДЕЛ прав
(app/training_content.py). Значит, добавленный в app/features.py раздел без
учебного блока молча выпадает из обучения: инструкция про него ничего не
скажет, тест ничего не спросит, и заметить это можно только случайно —
через полгода, когда человек не найдёт в материале того, чем пользуется
каждый день.

Скрипт отвечает на три вопроса:

  * какие разделы остались без блока (материал пишется этапами — это норма,
    но перечень должен быть виден);
  * есть ли блоки, ссылающиеся на несуществующий раздел (опечатка в ключе:
    такой блок не покажется никому);
  * нет ли вопросов с одинаковым ключом или с неверным индексом правильного
    ответа (первое портит историю прохождений, второе делает вопрос
    неотвечаемым).

Первое — предупреждение, остальное — ошибка (код возврата 1).

    .venv/bin/python scripts/check_training_coverage.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.features import FEATURES, FEATURES_BY_KEY  # noqa: E402
from app.training_content import (  # noqa: E402
    BLOCKS,
    CONTENT_VERSION,
    missing_features,
    unknown_blocks,
)


def main() -> int:
    ошибки = []

    нет_блока = missing_features()
    чужие = unknown_blocks()

    ключи = {}
    for блок in BLOCKS:
        for вопрос in блок.questions:
            if вопрос.key in ключи:
                ошибки.append(
                    f"вопрос «{вопрос.key}» встречается дважды: блоки "
                    f"«{ключи[вопрос.key]}» и «{блок.key}» — ключ должен быть уникален, "
                    f"по нему история прохождений находит вопрос")
            ключи[вопрос.key] = блок.key
            if not 0 <= вопрос.correct < len(вопрос.options):
                ошибки.append(
                    f"вопрос «{вопрос.key}»: правильный ответ {вопрос.correct}, "
                    f"а вариантов {len(вопрос.options)}")
            if len(вопрос.options) < 2:
                ошибки.append(f"вопрос «{вопрос.key}»: меньше двух вариантов ответа")
            if not вопрос.explain.strip():
                ошибки.append(
                    f"вопрос «{вопрос.key}»: нет разбора. Разбор обязателен — тест учит, "
                    f"а вопрос без объяснения это просто отметка о незнании")

    for ключ in чужие:
        ошибки.append(f"блок «{ключ}» ссылается на несуществующий раздел прав")

    print(f"Редакция материала: {CONTENT_VERSION}")
    print(f"Разделов прав: {len(FEATURES)}; блоков: {len(BLOCKS)}; вопросов: {len(ключи)}")

    if нет_блока:
        print(f"\nБЕЗ УЧЕБНОГО БЛОКА — {len(нет_блока)} из {len(FEATURES)}:")
        for ключ in нет_блока:
            раздел = FEATURES_BY_KEY[ключ]
            print(f"  · {раздел.section} → {раздел.title}  [{ключ}]")
        print("\nЭто предупреждение: материал пишется этапами. Но раздел, которым уже "
              "пользуются, обязан быть здесь описан.")
    else:
        print("\nВсе разделы прав описаны в учебном материале.")

    if ошибки:
        print("\nОШИБКИ:")
        for строка in ошибки:
            print(f"  ✗ {строка}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
