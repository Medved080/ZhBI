"""
Генератор синтетического тестового DXF для проверки разбора
структурированных имён слоёв + привязки элементов к
захваткам/кранам/стоянкам (см. Docs/backlog.md). Использует актуальную
(вторую) редакцию стандарта имён слоёв — WEB_констр_.../WEB_тех_...,
подтверждённую реальным чертежом "260715_Чертежи для WEB.dxf".

Геометрия (условные единицы, не привязаны к реальному масштабу здания):

  Захватка 1 — прямоугольник (0,0)-(1000,1000), название "Захватка 1"
  Захватка 2 — прямоугольник (1000,0)-(2000,1000), название "Захватка 2"
  Захватка 3 — прямоугольник (0,1200)-(1000,2200), БЕЗ названия рядом
               (текст "Наименование" отсутствует в этой зоне намеренно —
               проверка "элемент в зоне без сопоставленного названия")
  Кран       — Г-образная (невыпуклая) зона, покрывающая обе захватки 1/2 —
               проверка, что shapely корректно работает с невыпуклым контуром
  Стоянка A  — на отметке +15800, прямоугольник (0,0)-(400,400)
  Стоянка B  — на отметке +18800 (ДРУГОЙ уровень), тот же контур в плане —
               проверка, что элемент на уровне +15800 не цепляется к
               стоянке другого уровня, несмотря на геометрическое совпадение

Элементы:
  Колонна 1  — точка (200,200), внутри Захватки 1, отметка +15800
               (полностью однозначный случай — matched по всем применимым категориям)
  Ригель 1   — вытянутый прямоугольник (900,400)-(1100,600), СИММЕТРИЧНО на
               границе Захватки 1 и Захватки 2 (~50/50) — проверка needs_review
  Колонна 2  — точка (500,1700), внутри Захватки 3 (без названия) —
               проверка, что геометрическая привязка к зоне работает, даже
               если имя самой зоны не удалось определить

Запуск:
    python scripts/generate_test_zones_dxf.py
Результат:
    test_data/synthetic_zones.dxf
"""

import ezdxf

OUTPUT_PATH = "test_data/synthetic_zones.dxf"


def add_zone_polygon(msp, layer, points):
    msp.add_lwpolyline(points, close=True, dxfattribs={"layer": layer})


def add_name_text(msp, layer, text, position):
    msp.add_text(text, dxfattribs={"layer": layer, "height": 50}).set_placement(position)


def add_zhbi_polygon(msp, layer, points, mark, mark_layer):
    e = msp.add_lwpolyline(points, close=True, dxfattribs={"layer": layer})
    cx = sum(p[0] for p in points) / len(points)
    cy = sum(p[1] for p in points) / len(points)
    add_name_text(msp, mark_layer, mark, (cx, cy))
    return e


def main():
    doc = ezdxf.new("R2018", setup=True)
    doc.header["$INSUNITS"] = 4
    msp = doc.modelspace()

    # ---- Захватки ----
    add_zone_polygon(msp, "WEB_тех_Захватки_область", [(0, 0), (1000, 0), (1000, 1000), (0, 1000)])
    add_name_text(msp, "WEB_тех_Захватки_наименование", "Захватка 1", (500, 500))

    add_zone_polygon(msp, "WEB_тех_Захватки_область", [(1000, 0), (2000, 0), (2000, 1000), (1000, 1000)])
    add_name_text(msp, "WEB_тех_Захватки_наименование", "Захватка 2", (1500, 500))

    # Захватка 3 — намеренно без названия рядом
    add_zone_polygon(msp, "WEB_тех_Захватки_область", [(0, 1200), (1000, 1200), (1000, 2200), (0, 2200)])

    # ---- Кран (Г-образная, невыпуклая зона) ----
    add_zone_polygon(
        msp,
        "WEB_тех_Кран_область",
        [(0, 0), (2000, 0), (2000, 600), (600, 600), (600, 1000), (0, 1000)],
    )
    add_name_text(msp, "WEB_тех_Кран_наименование", "Кран 1", (300, 300))

    # ---- Стоянки (два разных уровня, одинаковая геометрия в плане) ----
    add_zone_polygon(msp, "WEB_тех_Стоянки крана_ОТМП15800_область", [(0, 0), (400, 0), (400, 400), (0, 400)])
    add_name_text(msp, "WEB_тех_Стоянки крана_ОТМП15800_наименование", "Стоянка A", (200, 200))

    add_zone_polygon(msp, "WEB_тех_Стоянки крана_ОТМП18800_область", [(0, 0), (400, 0), (400, 400), (0, 400)])
    add_name_text(msp, "WEB_тех_Стоянки крана_ОТМП18800_наименование", "Стоянка B", (200, 200))

    # ---- Элементы ЖБИ ----
    # Колонна 1 — точка внутри Захватки 1, отметка +15800 (совпадает со Стоянкой A)
    add_zhbi_polygon(
        msp, "WEB_констр_Колонна_ОТМП15800_элемент",
        [(150, 150), (250, 150), (250, 250), (150, 250)],
        "К1", "WEB_констр_Колонна_ОТМП15800_марка",
    )

    # Ригель 1 — на границе Захватки 1/2, без отметки (сквозной)
    add_zhbi_polygon(
        msp, "WEB_констр_Ригель_элемент",
        [(900, 400), (1100, 400), (1100, 600), (900, 600)],
        "Р1", "WEB_констр_Ригель_марка",
    )

    # Колонна 2 — внутри Захватки 3 (без сопоставленного названия), без отметки
    add_zhbi_polygon(
        msp, "WEB_констр_Колонна_элемент",
        [(450, 1650), (550, 1650), (550, 1750), (450, 1750)],
        "К2", "WEB_констр_Колонна_марка",
    )

    doc.saveas(OUTPUT_PATH)
    print(f"Сохранён тестовый файл: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
