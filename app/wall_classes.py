"""
Категории стен модели МФР — единое место для PDF и Revit.

У моделей из PDF материал стены известен по слою штриховки чертежа
(`app/pdf_rooms.py`, `_WALL_LAYERS`) и категория ставится сразу. У выгрузок
Revit штриховки нет: Revit отдаёт категорию «Стены» одной на всё, а различие
есть только в ИМЕНИ ТИПА стены («КЖ_ЖБ_200», «СВ_Газоблоки D500_200»,
«СВ_Кирпич_120»). Здесь — таблица «начало имени типа → категория»; по ней
стены Revit раскладываются на те же категории, что и у PDF (запрос
пользователя 2026-10-21: на тестовом сервере модель из Revit, и деление по
штриховке там не действует).

Правила написаны по реальным именам типов объекта-образца (81 тип стены).
Остальное — отделка («ОВ_…», «ОН_…»), утепление («УН_…», «УВ_…»), витражи,
прочее — остаётся «Стены»: отдельным слоем модели они не являются несущей
или ограждающей кладкой, и прятать их в «монолит» или «блоки» по суффиксу
основания («ОВ_Обои_ЖБ_20» — обои на ЖБ, а не бетонная стена) было бы ложью.
Новое имя типа добавляется строкой в `_RULES`; применить к уже загруженному —
обработка релиза (`app/release_tasks.py`, `_split_revit_walls`) или повторная
загрузка выгрузки.
"""

from typing import Optional

CAT_WALL = "Стены"
CAT_WALL_MONOLITH = "Стены монолит"
CAT_WALL_BLOCKS = "Стены блоки"
CAT_WALL_BRICK = "Стены кирпич"
CAT_PARTITION = "Перегородки"

# (начало имени типа без учёта регистра, категория). Первое совпадение
# побеждает. Начало, а не вхождение: «ОВ_Окраска…_Кирпич_20» — отделка,
# а не кирпичная стена.
_RULES = (
    # монолитный железобетон
    ("кж_жб", CAT_WALL_MONOLITH),
    ("стм_", CAT_WALL_MONOLITH),
    ("ар_кр_стена_сжб", CAT_WALL_MONOLITH),
    # кладка из блоков
    ("св_газоблоки", CAT_WALL_BLOCKS),
    ("сн стена_блок", CAT_WALL_BLOCKS),
    ("вс стена_кладка арм_блок", CAT_WALL_BLOCKS),
    # кирпичная кладка
    ("св_кирпич", CAT_WALL_BRICK),
    # перегородки: ГКЛ/ГКЛВ, каркасные «СТК», пазогребень, аквапанель
    ("св_гкл", CAT_PARTITION),
    ("стк ", CAT_PARTITION),
    ("св_пгп", CAT_PARTITION),
    ("св_аквапанель", CAT_PARTITION),
    ("мсу_перегородка", CAT_PARTITION),
)


def classify_revit_wall(category: Optional[str], type_name: Optional[str]) -> Optional[str]:
    """Категория для стены Revit по имени типа; для всего, что не «Стены» или
    не опознано, — исходная категория без изменений."""
    if category != CAT_WALL or not type_name:
        return category
    name = type_name.strip().casefold()
    for prefix, result in _RULES:
        if name.startswith(prefix):
            return result
    return category
