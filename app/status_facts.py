"""Дата факта изделия по истории статусов — одно определение на весь проект.

Решение пользователя 2026-10-23: изделие датируется ПОСЛЕДНЕЙ установкой, а не первой. Смонтировали, откатили на «Доставлен»,
смонтировали снова — факт этого изделия стоит на дне повторного монтажа. По первой отметке повторно смонтированное изделие
уходило в прошлый день, и «за сегодня» показывало меньше, чем смонтировано сегодня (36 смонтировано — в отчёте 30).

«Последняя установка» = начало ПОСЛЕДНЕЙ непрерывной серии записей из набора статусов: «Смонтирован» → «Принят» — одна серия,
«Смонтирован» → «Доставлен» → «Смонтирован» — две, берётся вторая. Порядок записей — тот же, которым система определяет текущий
статус: (changed_at, id).
"""
from typing import Iterable


def last_run_day_sql(statuses: Iterable[str], element_ref: str = "e.id") -> str:
    """SQL-подзапрос: дата (YYYY-MM-DD) начала последней серии статусов из набора у изделия `element_ref`; NULL — записей из
    набора нет. Статусы вставляются литералами (это внутренние коды, не ввод пользователя), поэтому подзапрос не меняет
    порядок параметров во внешнем запросе."""
    коды = tuple(statuses)
    assert коды and all(s.isidentifier() for s in коды), коды
    список = ",".join(f"'{s}'" for s in коды)
    return (
        f"(SELECT date(MIN(sh.changed_at)) FROM status_history sh "
        f"WHERE sh.element_id = {element_ref} AND sh.status IN ({список}) "
        f"AND NOT EXISTS (SELECT 1 FROM status_history x WHERE x.element_id = sh.element_id "
        f"AND x.status NOT IN ({список}) "
        f"AND (x.changed_at > sh.changed_at OR (x.changed_at = sh.changed_at AND x.id > sh.id))))"
    )
