def _in_docker() -> bool:
    return os.path.exists("/.dockerenv")


def _container() -> str:
    """Имя контейнера для docker-команд.

    В Docker hostname контейнера — это его короткий id, и `docker logs`/
    `docker exec` его принимают: команда получается готовой к выполнению.

    Вне Docker (запуск из venv на машине разработчика) подставляется
    УГЛОВАЯ СКОБКА, а не имя машины: `docker logs MacBook-Pro.local` — не
    просто бесполезная, а ЛОЖНАЯ команда, а памятка тем и ценна, что по ней
    действуют не перепроверяя.
    """
    return socket.gethostname() if _in_docker() else "<имя-контейнера>"


