def guide() -> dict:
    return {"facts": server_facts(), "sections": _sections()}


def as_markdown() -> str:
    """Тот же текст файлом — чтобы унести на свою машину и читать без сервиса
    (в том числе когда он как раз и не работает)."""
    строки = ["# Памятка администратора ЖБИ-трекера", ""]
    строки.append("## Этот сервер")
    строки.append("")
    for f in server_facts():
        строки.append(f"- **{f['name']}**: {f['value']}")
    строки.append("")
    for раздел in _sections():
        строки.append(f"## {раздел['title']}")
        строки.append("")
        строки.append(раздел["intro"])
        строки.append("")
        for пункт in раздел["items"]:
            строки.append(f"### {пункт['title']}")
            строки.append("")
            строки.append(f"_Где выполнять: {пункт['where']}_")
            строки.append("")
            строки.append(пункт["note"])
            if пункт["command"]:
                строки.append("")
                строки.append("```")
                строки.append(пункт["command"])
                строки.append("```")
            строки.append("")
    строки.append("---")
    строки.append("")
    строки.append("Подробности установки, схемы CI/CD и разбор частых сбоев — "
                  "`Docs/DEPLOYMENT_LINUX.md` в репозитории.")
    return "\n".join(строки)


@router.get("/admin-guide")
def read_admin_guide(admin: sqlite3.Row = Depends(require_service_feature("admin_guide", "read"))):
    return guide()


@router.get("/admin-guide.md")
def download_admin_guide(admin: sqlite3.Row = Depends(require_service_feature("admin_guide", "read"))):
    имя = "Памятка администратора ЖБИ.md"
    return Response(
        content=as_markdown(),
        media_type="text/markdown; charset=utf-8",
        headers={"Content-Disposition": "attachment; filename*=UTF-8''" + quote(имя)},
    )
