def help_for(key: str) -> dict:
    """Справка по одному отчёту или (DOC_HELP) документу. Неизвестный ключ — не ошибка: отчёт мог
    появиться раньше, чем его описание, и форма должна честно сказать об
    этом, а не упасть."""
    if key in DOC_HELP:      # справка к документу: без хвоста «Общее для всех отчётов»
        return {"key": key, **DOC_HELP[key]}
    данные = HELP.get(key)
    if данные is None:
        return {"key": key, "title": "Справка", "sections": [
            ("Описание ещё не написано",
             ["Для этого отчёта справка пока не заполнена (app/report_help.py)."])] + ОБЩЕЕ}
    return {"key": key, **данные, "sections": данные["sections"] + ОБЩЕЕ}
