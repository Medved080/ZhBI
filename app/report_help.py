def help_for(key: str) -> dict:
    """Справка по одному отчёту. Неизвестный ключ — не ошибка: отчёт мог
    появиться раньше, чем его описание, и форма должна честно сказать об
    этом, а не упасть."""
    данные = HELP.get(key)
    if данные is None:
        return {"key": key, "title": "Справка", "sections": [
            ("Описание ещё не написано",
             ["Для этого отчёта справка пока не заполнена (app/report_help.py)."])]}
    return {"key": key, **данные}
