def _axis_boundary_x(words) -> Optional[float]:
    """Граница между подписями осей секции 1 («…с1») и секции 2 («…с2»)
    в СЫРЫХ координатах листа (pt, до перевода в мм и сдвига). `None`, если
    на листе нет подписей обеих секций сразу (граница не определена — не
    гадаем, откуда её брать)."""
    s1_x = [w[0] for w in words if (m := _AXIS_RE.match(w[4])) and m.group(2) == "1"]
    s2_x = [w[0] for w in words if (m := _AXIS_RE.match(w[4])) and m.group(2) == "2"]
    if not s1_x or not s2_x:
        return None
    s1_max, s2_min = max(s1_x), min(s2_x)
    if s1_max >= s2_min:
        return None  # диапазоны пересеклись — на этом листе границе верить нельзя
    return (s1_max + s2_min) / 2


def _page_scale(page) -> int:
    m = _SCALE_RE.search(page.get_text())
    if not m:
        raise PdfRoomsError(
            "На листе не найден масштаб (подпись «М1:NNN») — без него "
            "координаты страницы нельзя перевести в миллиметры.")
    return int(m.group(1))


def _valid_outline(poly_mm: list) -> Optional[list]:
    """Контур помещения без самопересечений. Слой площадей рисует часть
    комнат «бантиком» — контур с самопересечением (на проверенном комплекте
    42 из 1239 помещений, по 1-3 на этаж; самый заметный — техническое
    пространство секции 1, 132 вершины): на плане это треугольные
    «лепестки» внутри комнаты, в 3D рваные грани, а площадь по Shoelace
    занижена (лепестки вычитаются). `make_valid` режет такой контур на
    доли (у «бантика» — большая доля плюс лепестки-щепки); берётся
    крупнейшая, с её ИСХОДНЫМИ вершинами — без склейки через
    `buffer(±1)`: та скругляет углы и раздувает контур в разы (57→368
    вершин на проверенном помещении).

    Чинится ТОЛЬКО когда крупнейшая доля сохраняет не меньше
    `_VALID_OUTLINE_MIN_KEEP` площади сырого контура — иначе контур не
    «бантик», а клубок петель (открытая парковка на листе 3: 13 долей,
    крупнейшая 989 из 1417 м²; фоновая заливка на листе 15: 16 долей), и
    отрезать от него две трети площади хуже, чем оставить как есть —
    такой контур возвращается сырым, как рисовался до этой правки.
    Валидный контур возвращается как есть — точки не переупорядочиваются."""
    if len(poly_mm) < 3:
        return None
    shape = Polygon(poly_mm)
    if shape.is_valid:
        return poly_mm

    def _polygons(g):
        if g.geom_type == "Polygon":
            return [g]
        return [p for sub in getattr(g, "geoms", []) for p in _polygons(sub)]

    parts = [p for p in _polygons(make_valid(shape)) if p.area > 0]
    if not parts:
        return poly_mm
    largest = max(parts, key=lambda p: p.area)
    if shape.area > 0 and largest.area < shape.area * _VALID_OUTLINE_MIN_KEEP:
        return poly_mm
    return [(x, y) for x, y in largest.exterior.coords[:-1]]


# Доля площади сырого контура, которую обязана сохранить крупнейшая доля
# после `make_valid`, чтобы починка считалась починкой, а не отсечением
# (см. `_valid_outline`): у «бантиков» 92-100%, у клубков петель 46-70%.
_VALID_OUTLINE_MIN_KEEP = 0.9


def _room_polygons(page, scale: int, correction: tuple = (0.0, 0.0)) -> tuple:
    """Полигоны слоя площадей — каждый СВОЕЙ фигурой, без объединения.
    Возвращает (полигоны, (сдвиг_x, сдвиг_y)).

    Сдвиг — выравнивание листа по верхнему правому углу застройки (сам угол
    становится (0,0)): у КАЖДОГО листа комплекта своя точка отсчёта на
    странице, а верхний правый угол здания при печати остаётся практически
    на месте от листа к листу (проверено на прототипе-«массе» этой же
    сессии: правый край 90469±20 мм, верхний край 73791..73841 мм у девяти
    разных листов). Без этого шага этажи с разных листов стояли бы в
    несовместимых координатах и не собрались бы в одно здание.

    `correction` — поправка (см. `_page_shift_correction`) для листов, чей
    верхний правый угол застройки физически ДРУГАЯ точка (подземный этаж,
    1-2 этажи — шире/уже типовой башни: парковка, вестибюль). Без неё их
    геометрия ложится в координаты СВОЕГО угла, а не в общую сетку осей
    объекта (`extract_axis_grid` берёт её с типового листа) — оси между
    этажами совпадают, а стены/помещения сдвинуты (2026-08-31, увидено
    пользователем на модели вживую)."""
    H = page.rect.height
    raw = []
    for d in page.get_cdrawings():
        if d.get("layer") != ROOM_LAYER or d["type"] != "f":
            continue
        pts = [it[1] for it in d["items"] if it[0] == "l"]
        if d["items"]:
            pts.append(d["items"][-1][2])
        if len(pts) < 3:
            continue
        bbox_area_pt = (d["rect"][2] - d["rect"][0]) * (d["rect"][3] - d["rect"][1])
        if bbox_area_pt < 20:
            continue  # шум — крошечные обрывки контура
        poly = [(x * PT_TO_MM * scale, (H - y) * PT_TO_MM * scale) for x, y in pts]
        raw.append(poly)
    if not raw:
        return [], (0.0, 0.0)
    shift_x = max(x for poly in raw for x, _ in poly) + correction[0]
    shift_y = max(y for poly in raw for _, y in poly) + correction[1]
    polys = [[(x - shift_x, y - shift_y) for x, y in poly] for poly in raw]
    return polys, (shift_x, shift_y)


_AXIS_ENVELOPE_MARGIN_MM = 3000
_WALL_COVERAGE_MIN = 0.5

def _axis_envelope(page, correction: tuple = (0.0, 0.0)) -> Optional[tuple]:
    """Охват здания по СЕТКЕ ОСЕЙ листа (`page_axis_labels`, включая
    вспомогательные — `_AXIS_AUX_RE`) — авторитетная граница «где на самом
    деле здание», а не эвристика: ось на чертеже — не случайное совпадение
    координат, а прямое утверждение проектировщика. Испробован и отброшен
    менее надёжный признак (2026-08-27): «нет подписанной площади» — не
    работает, у врезок площадь тоже часто есть (честная копия настоящей
    комнаты). Ось — тоже не абсолютная истина: это ЦЕНТР стены/колонны, не
    её грань, а иногда два РЕАЛЬНЫХ, но очень разных по сути случая
    (настоящее техпомещение у периметра и посторонняя заливка под текстом)
    оказываются на ПОЧТИ ОДИНАКОВОМ расстоянии от сетки (разница около
    100мм из 5000) — расстоянием одним их не развести. Поэтому здесь два
    порога: `_AXIS_ENVELOPE_MARGIN_MM` — уверенный допуск (толщина стены/
    консоль, оставляем без вопросов), дальше — решает не расстояние, а
    связность с реальной геометрией листа (`_perimeter_coverage` в
    `parse_page`). `None`, если на листе не нашлось ни одной подписи оси."""
    labels = page_axis_labels(page, correction)
    xs = [coord for _label, (направление, coord) in labels.items() if направление == "x"]
    ys = [coord for _label, (направление, coord) in labels.items() if направление == "y"]
    if not xs or not ys:
        return None
    return (min(xs), max(xs), min(ys), max(ys))


def _within_envelope(polygon_mm: list, envelope: tuple, margin: float = None) -> bool:
    x0, x1, y0, y1 = envelope
    m = _AXIS_ENVELOPE_MARGIN_MM if margin is None else margin
    xs = [p[0] for p in polygon_mm]
    ys = [p[1] for p in polygon_mm]
    return (x0 - m <= min(xs) and max(xs) <= x1 + m
            and y0 - m <= min(ys) and max(ys) <= y1 + m)


def _perimeter_coverage(polygon_mm: list, neighbors_mm: list, buf: float = 250) -> float:
    """Доля периметра полигона, покрытая соседями (другие помещения плюс
    СЫРЫЕ, ещё не отфильтрованные стены листа — `_wall_segments_raw`) в
    пределах `buf` мм. Настоящее помещение всегда к чему-то примыкает —
    хотя бы одной стороной к стене или соседней комнате через проём;
    заливка под одиночной подписью в пустом месте листа не примыкает ни к
    чему (проверено: 31% у подозрительного случая против 85% у
    настоящего далёкого техпомещения, 2026-08-27). Используется ТОЛЬКО
    для пограничных случаев (`parse_page`), не как общий признак — сама
    по себе связность подводила и в другую сторону (см. `_axis_envelope`,
    докстрока прежней версии в истории git)."""
    if not neighbors_mm:
        return 0.0
    boundary = Polygon(polygon_mm).exterior
    if boundary.length == 0:
        return 0.0
    near = unary_union([Polygon(p).buffer(buf) for p in neighbors_mm if len(p) >= 3])
    return boundary.intersection(near).length / boundary.length


# Подпись «Фрагмент…» («Фрагмент плана», «Фрагмент остекления») — прямое
# текстовое признание чертежа, что здесь ВРЕЗКА-ДЕТАЛЬ, а не сам план.
# Нужна отдельно от `_perimeter_coverage`: у дублирующей врезки часто
# нарисованы и свои (тоже дублирующие) стены, покрытие периметра у нёй
# от этого обманчиво высокое — ровно как у настоящего далёкого
# помещения (2026-08-27, «вестибюль» на этаже 1). Текст сильнее.
_FRAGMENT_LABEL_RE = re.compile(r'фрагмент', re.IGNORECASE)
_FRAGMENT_LABEL_RADIUS_MM = 30000


def _page_fragment_labels(page, scale: int, shift_x: float, shift_y: float) -> list:
    H = page.rect.height
    out = []
    for w in page.get_text("words"):
        if _FRAGMENT_LABEL_RE.match(w[4]):
            x_mm = w[0] * PT_TO_MM * scale - shift_x
            y_mm = (H - w[1]) * PT_TO_MM * scale - shift_y
            out.append((x_mm, y_mm))
    return out


def _near_fragment_label(polygon_mm: list, labels: list,
                         radius: float = _FRAGMENT_LABEL_RADIUS_MM) -> bool:
    if not labels:
        return False
    cx = sum(p[0] for p in polygon_mm) / len(polygon_mm)
    cy = sum(p[1] for p in polygon_mm) / len(polygon_mm)
    return any((cx - lx) ** 2 + (cy - ly) ** 2 <= radius ** 2 for lx, ly in labels)


def _page_section_boundary_mm(page, correction: tuple = (0.0, 0.0)) -> Optional[float]:
    """Граница осей секций 1/2 листа (`_axis_boundary_x`) в тех же
    выровненных мм-координатах, что и контуры помещений/стен. Секция 1 —
    ВСЕГДА левее границы, секция 2 — правее (`_axis_boundary_x`,
    докстрока: `s1_max < s2_min`).

    Нужна не только для подписи секции у общих этажей 1-8, но и для
    ПОЛНОГО СРЕЗА на этажах с ЕДИНСТВЕННОЙ секцией — в обе стороны
    (замечено пользователем 2026-08-27, уточнено 2026-09-01): выше 8-го
    этажа у каждой секции СВОИ, разные по высоте, ярусы, и лист одного
    яруса нередко показывает СОСЕДНИЙ ярус другой секции «для информации»
    (кровля секции 2 на листах 10-11 секции 1 и наоборот, технические
    пространства секции 1 на листах 10-11 секции 2) — там нет ни одного
    элемента ЭТОГО этажа, а плановая и стеновая геометрия по другую
    сторону границы всё равно присутствует на листе и, будучи заведомо в
    пределах сетки осей здания (`_axis_envelope` её не отсечёт — это тоже
    часть корпуса, просто другого яруса), иначе просочилась бы в модель
    как элементы несуществующего на этом этаже участка."""
    scale = _page_scale(page)
    _, (shift_x, _shift_y) = _room_polygons(page, scale, correction)
    boundary_pt = _axis_boundary_x(page.get_text("words"))
    if boundary_pt is None:
        return None
    return boundary_pt * PT_TO_MM * scale - shift_x


_ROOM_BBOX_RATIO_MAX = 0.4


def _drop_oversized_rooms(rooms: list, area_label_points: list = None) -> tuple:
    """Полигон, чей габарит — почти весь этаж (доля от габарита ОХВАТА
    ВСЕХ помещений листа выше `_ROOM_BBOX_RATIO_MAX`), — не отдельное
    помещение, а фоновая заливка/штриховка на весь этаж (найдено
    2026-08-27 на двух листах: 259 и 145 вершин, доля 86% и 100% — у
    настоящих, даже сложных по форме помещений на тех же листах доля не
    больше 10%). Отбрасывается ДО сопоставления площади (иначе гигантский
    полигон перехватывает подпись площади ближайшей настоящей комнаты,
    накрывая её собой).

    ИСКЛЮЧЕНИЕ (2026-08-31, живой найдено пользователем — «один блок без
    деления», открытая парковка на подземном этаже): открытая парковка —
    ТОЖЕ огромный по габариту полигон (86% в одном проверенном случае —
    то самое число из примера выше; выходит, свою же калибровку эта
    эвристика когда-то и отбрасывала), но НАСТОЯЩИЙ, не заливка — внутри
    у него своя подпись площади («1 199,7 м²» на проверенном чертеже).
    `area_label_points` — координаты (мм) уже найденных на листе подписей
    «<число> м²» (тот же признак, каким ниже площадь сопоставляется
    помещениям): у декоративной заливки такой подписи внутри не бывает
    вовсе — точка, а не площадь, разводит эти два случая безопасно, не
    ослабляя эвристику для настоящих обрывков штриховки.

    Спасённая комната сразу помечается СВОЕЙ секцией «Паркинг»
    (2026-08-31, прямое уточнение пользователя со скриншотом — у зоны
    паркинга свои оси и чёткая прямоугольная граница, отдельная от С01/
    С02, а не их объединение): `parse_page` уважает уже проставленную
    секцию и не пересчитывает её по границе `С01`/`С02`. Возвращает
    (оставшиеся, отброшенные)."""
    if len(rooms) < 2:
        return rooms, []
    xs = [x for r in rooms for x, _ in r.polygon_mm]
    ys = [y for r in rooms for _, y in r.polygon_mm]
    total_area = (max(xs) - min(xs)) * (max(ys) - min(ys))
    if total_area <= 0:
        return rooms, []
    label_points = [Point(x, y) for x, y in (area_label_points or [])]
    kept, dropped = [], []
    for r in rooms:
        rxs = [x for x, _ in r.polygon_mm]
        rys = [y for _, y in r.polygon_mm]
        own_bbox = (max(rxs) - min(rxs)) * (max(rys) - min(rys))
        if own_bbox / total_area <= _ROOM_BBOX_RATIO_MAX:
            kept.append(r)
            continue
        poly = Polygon(r.polygon_mm)
        if any(poly.contains(p) for p in label_points):
            r.section = _PARKING_SECTION
            kept.append(r)
        else:
            dropped.append(r)
    return kept, dropped


def parse_page(page, correction: tuple = (0.0, 0.0)) -> tuple:
    """Возвращает (список Room с пустым `floor`, предупреждения). `floor`
    проставляется вызывающим кодом — одна страница может обслуживать
    несколько физических этажей (типовые планы). Порядок и `index` —
    по центроиду контура (сначала сверху вниз, потом слева направо в
    координатах листа), детерминированно от запуска к запуску.

    `correction` — см. `_room_polygons`/`_page_shift_correction`: поправка
    сдвига листа под общую сетку осей объекта, для листов с нетиповым
    верхним правым углом застройки (подземный этаж, 1-2 этажи)."""
    scale = _page_scale(page)
    H = page.rect.height
    polygons_mm, (shift_x, shift_y) = _room_polygons(page, scale, correction)

    def centroid_key(poly):
        n = len(poly)
        cx = sum(p[0] for p in poly) / n
        cy = sum(p[1] for p in poly) / n
        return (-round(cy), round(cx))  # сверху вниз (Y уже инвертирован в мм)

    words = page.get_text("words")

    def to_mm(x_pt, y_pt):
        return (x_pt * PT_TO_MM * scale - shift_x,
                (H - y_pt) * PT_TO_MM * scale - shift_y)

    # Те же подписи «<число> м²», что ниже сопоставляются помещениям —
    # нужны РАНЬШЕ, чтобы отличить настоящую большую комнату (открытая
    # парковка целиком, с подписанной площадью) от декоративной заливки
    # без единой подписи внутри (`_drop_oversized_rooms`).
    area_label_points = [
        to_mm(w[0], w[1]) for i, w in enumerate(words)
        if _AREA_RE.match(w[4]) and i + 1 < len(words)
        and "м2" in words[i + 1][4].replace("²", "2")
    ]

    polygons_mm.sort(key=centroid_key)
    rooms = [Room(floor="", index=i, polygon_mm=poly)
            for i, poly in enumerate(polygons_mm)]
    rooms, oversized = _drop_oversized_rooms(rooms, area_label_points)
    for i, r in enumerate(rooms):
        r.index = i
    shapely_rooms = [Polygon(r.polygon_mm) for r in rooms]

    # секция: центроид комнаты по одну или другую сторону границы осей
    # «…с1»/«…с2» (см. _axis_boundary_x) — считается один раз на лист, в
    # тех же сырых координатах (pt), что и сами подписи осей. Комнату с
    # УЖЕ проставленной секцией (парковка, `_drop_oversized_rooms`) не
    # трогаем — у неё своя, не по границе С01/С02.
    boundary_pt = _axis_boundary_x(words)
    if boundary_pt is not None:
        boundary_mm = boundary_pt * PT_TO_MM * scale - shift_x
        for room, poly in zip(rooms, shapely_rooms):
            if room.section is not None:
                continue
            cx = poly.centroid.x
            room.section = "С01" if cx < boundary_mm else "С02"

    # площадь: число вида «14,3» рядом со словом «м2», центр — в комнате
    matched_area = 0
    for i, w in enumerate(words):
        if not _AREA_RE.match(w[4]):
            continue
        nxt = words[i + 1] if i + 1 < len(words) else None
        if not nxt or "м2" not in nxt[4].replace("²", "2"):
            continue
        px, py = to_mm(w[0], w[1])
        point = Point(px, py)
        for room, poly in zip(rooms, shapely_rooms):
            if poly.contains(point):
                room.area_m2 = float(w[4].replace(",", "."))
                matched_area += 1
                break

    # врезки — каталог типов квартир, «ФРАГМЕНТ ПЛАНА» и т.п., тем же слоем
    # помещений, что и сам план (см. докстрока `_axis_envelope`) — вне
    # уверенного допуска сетки осей отбрасываются; в пограничной зоне
    # решает не расстояние, а связность с реальной геометрией листа
    # (`_perimeter_coverage`) — расстояние одно там не разводит настоящее
    # от постороннего (см. докстрока `_axis_envelope`).
    envelope = _axis_envelope(page, correction)
    if envelope is not None:
        inside = [r for r in rooms if _within_envelope(r.polygon_mm, envelope)]
        outside = [r for r in rooms if not _within_envelope(r.polygon_mm, envelope)]
        dropped = []
        if outside:
            raw_walls = [w["polygon_mm"] for w in _wall_segments_raw(page, scale, shift_x, shift_y)]
            fragment_labels = _page_fragment_labels(page, scale, shift_x, shift_y)
            all_polys = [r.polygon_mm for r in rooms]
            for r in outside:
                # подпись «Фрагмент…» сильнее связности: у врезки бывают
                # свои (дублирующие) стены, покрытие периметра обманчиво.
                if _near_fragment_label(r.polygon_mm, fragment_labels):
                    dropped.append(r)
                    continue
                neighbors = [p for p in all_polys if p is not r.polygon_mm] + raw_walls
                if _perimeter_coverage(r.polygon_mm, neighbors) >= _WALL_COVERAGE_MIN:
                    inside.append(r)
                else:
                    dropped.append(r)
        rooms = inside
    else:
        dropped = []
    for i, r in enumerate(rooms):
        r.index = i  # переиндексация после отбрасывания — без разрывов
        # Контур чинится В САМОМ КОНЦЕ, когда состав помещений листа уже
        # решён: все эвристики выше (подпись площади внутри, отсев фоновой
        # заливки, охват осей, связность) откалиброваны на СЫРЫХ контурах,
        # и починка до них меняла их исход (2026-09-01: фоновая заливка на
        # весь этаж на листе 15 из невалидной становилась валидной и
        # «спасалась» как паркинг, а настоящий паркинг на листе 3 терялся).
        r.polygon_mm = _valid_outline(r.polygon_mm) or r.polygon_mm

    warnings = []
    if rooms and matched_area < len(rooms) * 0.5:
        warnings.append(
            f"площадь найдена только у {matched_area} из {len(rooms)} "
            "помещений — проверьте разбор этого листа отдельно")
    if rooms and boundary_pt is None:
        warnings.append(
            "граница осей секций не определена (нет подписей «…с1»/«…с2» "
            "обеих секций сразу) — секция помещений этого листа не проставлена")
    if envelope is None:
        warnings.append(
            "на листе не нашлось ни одной подписи оси — врезки (каталог "
            "типов квартир, «Фрагмент плана» и т.п.), если они есть, не "
            "отфильтрованы")
    if dropped:
        площади = ", ".join(
            (f"{r.area_m2}" if r.area_m2 is not None else "без площади") for r in dropped)
        warnings.append(
            f"{len(dropped)} фигур(ы) слоя помещений отброшены как врезка "
            f"(каталог типов квартир, «Фрагмент плана» и т.п. — вне сетки "
            f"осей листа, не элементы схемы): {площади}")
    if oversized:
        warnings.append(
            f"{len(oversized)} фигур(ы) слоя помещений отброшены как фоновая "
            f"заливка на весь этаж (габарит почти во весь охват листа — не "
            f"отдельное помещение), не элементы схемы")
    return rooms, warnings


def parse_document(doc, on_progress=None) -> tuple:
    """Разбор всего комплекта по FLOOR_PLANS. `doc` — уже открытый
    `fitz.Document` (см. `load()`). `on_progress(номер_листа, разобрано,
    всего)` — необязательный колбэк, вызывается после разбора КАЖДОГО
    уникального листа (тяжёлая часть — само чтение геометрии PDF, секунды
    на лист; листы, общие для нескольких этажей типового плана,
    разбираются один раз и колбэк для них не повторяется) — единственный
    практичный способ показать прогресс долгой загрузки (2026-08-31,
    прямой запрос пользователя: "сколько ещё ждать"). `разобрано`/`всего`
    — счётчик и общее число УНИКАЛЬНЫХ листов (не то же самое, что номер
    листа в PDF: страниц в файле может быть 22, а уникальных листов планов
    среди них — 12, страницы вразнобой — 3, 5, 8, 15… «номер листа» и
    «всего» разной природы, показывать их как N из M нельзя, ровно это и
    спутало пользователя на первой версии прогресс-бара). Возвращает
    (список Room, предупреждения).

    Каждый лист разбирается с поправкой (`_page_shift_correction`) под
    каноническую сетку осей объекта (`extract_axis_grid`) — иначе
    геометрия нетиповых листов (подземный этаж, 1-2 этажи) ложится в
    координаты СВОЕГО угла застройки, а не в общую сетку (см. докстроку
    `_page_shift_correction`)."""
    all_rooms = []
    warnings = []
    page_cache = {}
    canonical_grid = extract_axis_grid(doc)
    total_pages = len({plan.page for plan in FLOOR_PLANS})
    processed = 0
    for plan in FLOOR_PLANS:
        if plan.page not in page_cache:
            page = doc[plan.page - 1]
            try:
                correction = _page_shift_correction(page, canonical_grid)
                rooms, page_warnings = parse_page(page, correction)
                boundary_mm = _page_section_boundary_mm(page, correction)
            except PdfRoomsError as e:
                warnings.append(f"Лист {plan.page} (этаж {plan.floor}): {e.message}")
                rooms, page_warnings, boundary_mm = [], [], None
            page_cache[plan.page] = (rooms, page_warnings, boundary_mm)
            processed += 1
            if on_progress:
                on_progress(plan.page, processed, total_pages)
        rooms, page_warnings, boundary_mm = page_cache[plan.page]
        for w in page_warnings:
            warnings.append(f"Лист {plan.page} (этаж {plan.floor}): {w}")
        # Этаж с ОДНОЙ возможной секцией — она известна из таблицы этажей
        # надёжнее любой геометрии; определение по осям только для этажей,
        # общих для нескольких секций (иначе шум на границе листа мог бы
        # переспорить заведомо известный факт).
        known_section = plan.section_codes[0] if len(plan.section_codes) == 1 else None
        floor_rooms = rooms
        # Секция 1 на листах этажей выше 8-го показана «для информации»
        # (кровля/техчасть) — у ЭТОГО этажа её нет вовсе (замечено
        # пользователем 2026-08-27): всё левее границы осей секций
        # отбрасывается для единственно-секционных этажей целиком, не
        # просто переподписывается.
        if known_section == "С02" and boundary_mm is not None:
            def _cx(r):
                return sum(x for x, _ in r.polygon_mm) / len(r.polygon_mm)
            excluded = [r for r in floor_rooms if _cx(r) < boundary_mm]
            if excluded:
                warnings.append(
                    f"Лист {plan.page} (этаж {plan.floor}): {len(excluded)} "
                    "помещений(-ие) левее границы секций — секция 1 «для "
                    "информации» на этом листе, у этажа её нет, отброшены")
            floor_rooms = [r for r in floor_rooms if _cx(r) >= boundary_mm]
        # Зеркальный случай (2026-09-01, живая правка пользователя —
        # выше 8-го этажа у секции 1 ЕСТЬ собственные ярусы: техническое
        # пространство и выход на кровлю, листы 10 и 11 показывают их
        # рядом с типовым этажом секции 2 на том же листе): всё ПРАВЕЕ
        # границы осей секций отбрасывается для единственно-секционных
        # этажей секции 1.
        if known_section == "С01" and boundary_mm is not None:
            def _cx(r):
                return sum(x for x, _ in r.polygon_mm) / len(r.polygon_mm)
            excluded = [r for r in floor_rooms if _cx(r) >= boundary_mm]
            if excluded:
                warnings.append(
                    f"Лист {plan.page} (этаж {plan.floor}): {len(excluded)} "
                    "помещений(-ие) правее границы секций — секция 2 на "
                    "этом листе относится к другому этажу, отброшены")
            floor_rooms = [r for r in floor_rooms if _cx(r) < boundary_mm]
        for i, r in enumerate(floor_rooms):
            all_rooms.append(Room(floor=plan.floor, index=i,
                                  polygon_mm=r.polygon_mm, area_m2=r.area_m2,
                                  section=known_section or r.section,
                                  page=plan.page))
    return all_rooms, warnings


# Разметка машиномест лежит на том же слое, что монолитный бетон
# (`]]]_СТ_вн_Бетон`), и тоже заливкой — по слою/типу от настоящей стены
# не отличить (2026-08-31, прямое указание пользователя на разбор той же
# парковки: жёлтым — просто границы места, зелёным — настоящие
# несущие стены, других стен в зоне парковки нет). Разводит ЦВЕТ заливки:
# на всём листе подвала это ровно 74 фигуры, все — этот жёлтый и только
# на этом слое (проверено), у остальных материалов такого цвета нет нигде
# в комплекте — яркий жёлтый для железобетона/кирпича/газобетона не
# используется никем, это цвет разметки, а не материала.
_MARKING_FILL_COLOR = (0.925, 0.925, 0.0)
_MARKING_FILL_TOLERANCE = 0.02


def _is_marking_fill(fill) -> bool:
    if not fill:
        return False
    return all(abs(c - m) <= _MARKING_FILL_TOLERANCE
              for c, m in zip(fill, _MARKING_FILL_COLOR))


def _wall_segments_raw(page, scale: int, shift_x: float, shift_y: float) -> list:
    """Залитые прямоугольники слоёв материала стен (`_WALL_LAYERS`) на
    ВСЁМ листе — легенда материалов ещё не отсечена (см. `parse_walls_
    page`). Один прямоугольник — один ПРЯМОЙ участок стены: под
    штриховкой (тысячи мелких обрывков линий, `type == "s"`, о них
    докстрока модуля) лежит настоящая заливка (`type == "f"`) — по одной
    фигуре на прямой кусок стены между углами/проёмами, толщина —
    короткая сторона её прямоугольника. `shift_x`/`shift_y` — тот же сдвиг
    выравнивания, что и у `_room_polygons` (передаётся, а не считается
    заново — один и тот же для всех слоёв листа). Разметка машиномест
    (`_is_marking_fill`) исключается — не материал, а линия по месту."""
    H = page.rect.height
    out = []
    for d in page.get_cdrawings():
        spec = _WALL_LAYERS.get(d.get("layer"))
        if not spec or d["type"] != "f" or _is_marking_fill(d.get("fill")):
            continue
        pts = [it[1] for it in d["items"] if it[0] == "l"]
        if d["items"]:
            pts.append(d["items"][-1][2])
        if len(pts) < 3:
            continue
        rect = d["rect"]
        if (rect[2] - rect[0]) * (rect[3] - rect[1]) < 0.05:
            continue  # шум — точечные обрывки контура
        poly = [(x * PT_TO_MM * scale - shift_x, (H - y) * PT_TO_MM * scale - shift_y)
                for x, y in pts]
        category, material = spec
        thickness = round(min(rect[2] - rect[0], rect[3] - rect[1]) * PT_TO_MM * scale, 1)
        out.append({"category": category, "material": material,
                    "polygon_mm": poly, "thickness_mm": thickness})
    return out


