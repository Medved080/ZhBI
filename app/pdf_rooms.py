def _axis_boundary_x(words) -> Optional[float]:
    """Граница между подписями осей секции 1 («…с1») и секции 2 («…с2»)
    в СЫРЫХ координатах листа (pt, до перевода в мм и сдвига). `None`, если
    на листе нет подписей обеих секций сразу (граница не определена — не
    гадаем, откуда её брать)."""
    s1_x = [w[0] for w in words if (m := _AXIS_RE.match(w[4])) and m.group(2) == "1"]
    s2_x = [w[0] for w in words if (m := _AXIS_RE.match(w[4])) and m.group(2) == "2"]
    if not s1_x or not s2_x:
        return None
    s1_max, s2_min = max(s1_x), min(s2_x)
    if s1_max >= s2_min:
        return None  # диапазоны пересеклись — на этом листе границе верить нельзя
    return (s1_max + s2_min) / 2


def _page_scale(page) -> int:
    m = _SCALE_RE.search(page.get_text())
    if not m:
        raise PdfRoomsError(
            "На листе не найден масштаб (подпись «М1:NNN») — без него "
            "координаты страницы нельзя перевести в миллиметры.")
    return int(m.group(1))


def _room_polygons(page, scale: int) -> tuple:
    """Полигоны слоя площадей — каждый СВОЕЙ фигурой, без объединения.
    Возвращает (полигоны, (сдвиг_x, сдвиг_y)).

    Сдвиг — выравнивание листа по верхнему правому углу застройки (сам угол
    становится (0,0)): у КАЖДОГО листа комплекта своя точка отсчёта на
    странице, а верхний правый угол здания при печати остаётся практически
    на месте от листа к листу (проверено на прототипе-«массе» этой же
    сессии: правый край 90469±20 мм, верхний край 73791..73841 мм у девяти
    разных листов). Без этого шага этажи с разных листов стояли бы в
    несовместимых координатах и не собрались бы в одно здание."""
    H = page.rect.height
    raw = []
    for d in page.get_cdrawings():
        if d.get("layer") != ROOM_LAYER or d["type"] != "f":
            continue
        pts = [it[1] for it in d["items"] if it[0] == "l"]
        if d["items"]:
            pts.append(d["items"][-1][2])
        if len(pts) < 3:
            continue
        bbox_area_pt = (d["rect"][2] - d["rect"][0]) * (d["rect"][3] - d["rect"][1])
        if bbox_area_pt < 20:
            continue  # шум — крошечные обрывки контура
        poly = [(x * PT_TO_MM * scale, (H - y) * PT_TO_MM * scale) for x, y in pts]
        raw.append(poly)
    if not raw:
        return [], (0.0, 0.0)
    shift_x = max(x for poly in raw for x, _ in poly)
    shift_y = max(y for poly in raw for _, y in poly)
    polys = [[(x - shift_x, y - shift_y) for x, y in poly] for poly in raw]
    return polys, (shift_x, shift_y)


_AXIS_ENVELOPE_MARGIN_MM = 3000
_WALL_COVERAGE_MIN = 0.5

def _axis_envelope(page) -> Optional[tuple]:
    """Охват здания по СЕТКЕ ОСЕЙ листа (`page_axis_labels`, включая
    вспомогательные — `_AXIS_AUX_RE`) — авторитетная граница «где на самом
    деле здание», а не эвристика: ось на чертеже — не случайное совпадение
    координат, а прямое утверждение проектировщика. Испробован и отброшен
    менее надёжный признак (2026-08-27): «нет подписанной площади» — не
    работает, у врезок площадь тоже часто есть (честная копия настоящей
    комнаты). Ось — тоже не абсолютная истина: это ЦЕНТР стены/колонны, не
    её грань, а иногда два РЕАЛЬНЫХ, но очень разных по сути случая
    (настоящее техпомещение у периметра и посторонняя заливка под текстом)
    оказываются на ПОЧТИ ОДИНАКОВОМ расстоянии от сетки (разница около
    100мм из 5000) — расстоянием одним их не развести. Поэтому здесь два
    порога: `_AXIS_ENVELOPE_MARGIN_MM` — уверенный допуск (толщина стены/
    консоль, оставляем без вопросов), дальше — решает не расстояние, а
    связность с реальной геометрией листа (`_perimeter_coverage` в
    `parse_page`). `None`, если на листе не нашлось ни одной подписи оси."""
    labels = page_axis_labels(page)
    xs = [coord for _label, (направление, coord) in labels.items() if направление == "x"]
    ys = [coord for _label, (направление, coord) in labels.items() if направление == "y"]
    if not xs or not ys:
        return None
    return (min(xs), max(xs), min(ys), max(ys))


def _within_envelope(polygon_mm: list, envelope: tuple, margin: float = None) -> bool:
    x0, x1, y0, y1 = envelope
    m = _AXIS_ENVELOPE_MARGIN_MM if margin is None else margin
    xs = [p[0] for p in polygon_mm]
    ys = [p[1] for p in polygon_mm]
    return (x0 - m <= min(xs) and max(xs) <= x1 + m
            and y0 - m <= min(ys) and max(ys) <= y1 + m)


def _perimeter_coverage(polygon_mm: list, neighbors_mm: list, buf: float = 250) -> float:
    """Доля периметра полигона, покрытая соседями (другие помещения плюс
    СЫРЫЕ, ещё не отфильтрованные стены листа — `_wall_segments_raw`) в
    пределах `buf` мм. Настоящее помещение всегда к чему-то примыкает —
    хотя бы одной стороной к стене или соседней комнате через проём;
    заливка под одиночной подписью в пустом месте листа не примыкает ни к
    чему (проверено: 31% у подозрительного случая против 85% у
    настоящего далёкого техпомещения, 2026-08-27). Используется ТОЛЬКО
    для пограничных случаев (`parse_page`), не как общий признак — сама
    по себе связность подводила и в другую сторону (см. `_axis_envelope`,
    докстрока прежней версии в истории git)."""
    if not neighbors_mm:
        return 0.0
    boundary = Polygon(polygon_mm).exterior
    if boundary.length == 0:
        return 0.0
    near = unary_union([Polygon(p).buffer(buf) for p in neighbors_mm if len(p) >= 3])
    return boundary.intersection(near).length / boundary.length


# Подпись «Фрагмент…» («Фрагмент плана», «Фрагмент остекления») — прямое
# текстовое признание чертежа, что здесь ВРЕЗКА-ДЕТАЛЬ, а не сам план.
# Нужна отдельно от `_perimeter_coverage`: у дублирующей врезки часто
# нарисованы и свои (тоже дублирующие) стены, покрытие периметра у нёй
# от этого обманчиво высокое — ровно как у настоящего далёкого
# помещения (2026-08-27, «вестибюль» на этаже 1). Текст сильнее.
_FRAGMENT_LABEL_RE = re.compile(r'фрагмент', re.IGNORECASE)
_FRAGMENT_LABEL_RADIUS_MM = 30000


def _page_fragment_labels(page, scale: int, shift_x: float, shift_y: float) -> list:
    H = page.rect.height
    out = []
    for w in page.get_text("words"):
        if _FRAGMENT_LABEL_RE.match(w[4]):
            x_mm = w[0] * PT_TO_MM * scale - shift_x
            y_mm = (H - w[1]) * PT_TO_MM * scale - shift_y
            out.append((x_mm, y_mm))
    return out


def _near_fragment_label(polygon_mm: list, labels: list,
                         radius: float = _FRAGMENT_LABEL_RADIUS_MM) -> bool:
    if not labels:
        return False
    cx = sum(p[0] for p in polygon_mm) / len(polygon_mm)
    cy = sum(p[1] for p in polygon_mm) / len(polygon_mm)
    return any((cx - lx) ** 2 + (cy - ly) ** 2 <= radius ** 2 for lx, ly in labels)


def _page_section_boundary_mm(page) -> Optional[float]:
    """Граница осей секций 1/2 листа (`_axis_boundary_x`) в тех же
    выровненных мм-координатах, что и контуры помещений/стен. Секция 1 —
    ВСЕГДА левее границы, секция 2 — правее (`_axis_boundary_x`,
    докстрока: `s1_max < s2_min`).

    Нужна не только для подписи секции у общих этажей 1-8, но и для
    ПОЛНОГО СРЕЗА на этажах с ЕДИНСТВЕННОЙ секцией (замечено пользователем
    2026-08-27): на этажах выше 8-го секция 1 на листе показана «для
    информации» (кровля/техническая часть) — там нет ни одного элемента
    ЭТОГО этажа, а плановая и стеновая геометрия слева от границы всё
    равно присутствует на листе и, будучи заведомо в пределах сетки осей
    здания (`_axis_envelope` её не отсечёт — это тоже часть корпуса,
    просто другой секции), иначе просочилась бы в модель как элементы
    несуществующего на этом этаже участка."""
    scale = _page_scale(page)
    _, (shift_x, _shift_y) = _room_polygons(page, scale)
    boundary_pt = _axis_boundary_x(page.get_text("words"))
    if boundary_pt is None:
        return None
    return boundary_pt * PT_TO_MM * scale - shift_x


_ROOM_BBOX_RATIO_MAX = 0.4


def _drop_oversized_rooms(rooms: list, area_label_points: list = None) -> tuple:
    """Полигон, чей габарит — почти весь этаж (доля от габарита ОХВАТА
    ВСЕХ помещений листа выше `_ROOM_BBOX_RATIO_MAX`), — не отдельное
    помещение, а фоновая заливка/штриховка на весь этаж (найдено
    2026-08-27 на двух листах: 259 и 145 вершин, доля 86% и 100% — у
    настоящих, даже сложных по форме помещений на тех же листах доля не
    больше 10%). Отбрасывается ДО сопоставления площади (иначе гигантский
    полигон перехватывает подпись площади ближайшей настоящей комнаты,
    накрывая её собой).

    ИСКЛЮЧЕНИЕ (2026-08-31, живой найдено пользователем — «один блок без
    деления», открытая парковка на подземном этаже): открытая парковка —
    ТОЖЕ огромный по габариту полигон (86% в одном проверенном случае —
    то самое число из примера выше; выходит, свою же калибровку эта
    эвристика когда-то и отбрасывала), но НАСТОЯЩИЙ, не заливка — внутри
    у него своя подпись площади («1 199,7 м²» на проверенном чертеже).
    `area_label_points` — координаты (мм) уже найденных на листе подписей
    «<число> м²» (тот же признак, каким ниже площадь сопоставляется
    помещениям): у декоративной заливки такой подписи внутри не бывает
    вовсе — точка, а не площадь, разводит эти два случая безопасно, не
    ослабляя эвристику для настоящих обрывков штриховки.

    Спасённая комната сразу помечается СВОЕЙ секцией «Паркинг»
    (2026-08-31, прямое уточнение пользователя со скриншотом — у зоны
    паркинга свои оси и чёткая прямоугольная граница, отдельная от С01/
    С02, а не их объединение): `parse_page` уважает уже проставленную
    секцию и не пересчитывает её по границе `С01`/`С02`. Возвращает
    (оставшиеся, отброшенные)."""
    if len(rooms) < 2:
        return rooms, []
    xs = [x for r in rooms for x, _ in r.polygon_mm]
    ys = [y for r in rooms for _, y in r.polygon_mm]
    total_area = (max(xs) - min(xs)) * (max(ys) - min(ys))
    if total_area <= 0:
        return rooms, []
    label_points = [Point(x, y) for x, y in (area_label_points or [])]
    kept, dropped = [], []
    for r in rooms:
        rxs = [x for x, _ in r.polygon_mm]
        rys = [y for _, y in r.polygon_mm]
        own_bbox = (max(rxs) - min(rxs)) * (max(rys) - min(rys))
        if own_bbox / total_area <= _ROOM_BBOX_RATIO_MAX:
            kept.append(r)
            continue
        poly = Polygon(r.polygon_mm)
        if any(poly.contains(p) for p in label_points):
            r.section = _PARKING_SECTION
            kept.append(r)
        else:
            dropped.append(r)
    return kept, dropped


def parse_page(page) -> tuple:
    """Возвращает (список Room с пустым `floor`, предупреждения). `floor`
    проставляется вызывающим кодом — одна страница может обслуживать
    несколько физических этажей (типовые планы). Порядок и `index` —
    по центроиду контура (сначала сверху вниз, потом слева направо в
    координатах листа), детерминированно от запуска к запуску."""
    scale = _page_scale(page)
    H = page.rect.height
    polygons_mm, (shift_x, shift_y) = _room_polygons(page, scale)

    def centroid_key(poly):
        n = len(poly)
        cx = sum(p[0] for p in poly) / n
        cy = sum(p[1] for p in poly) / n
        return (-round(cy), round(cx))  # сверху вниз (Y уже инвертирован в мм)

    words = page.get_text("words")

    def to_mm(x_pt, y_pt):
        return (x_pt * PT_TO_MM * scale - shift_x,
                (H - y_pt) * PT_TO_MM * scale - shift_y)

    # Те же подписи «<число> м²», что ниже сопоставляются помещениям —
    # нужны РАНЬШЕ, чтобы отличить настоящую большую комнату (открытая
    # парковка целиком, с подписанной площадью) от декоративной заливки
    # без единой подписи внутри (`_drop_oversized_rooms`).
    area_label_points = [
        to_mm(w[0], w[1]) for i, w in enumerate(words)
        if _AREA_RE.match(w[4]) and i + 1 < len(words)
        and "м2" in words[i + 1][4].replace("²", "2")
    ]

    polygons_mm.sort(key=centroid_key)
    rooms = [Room(floor="", index=i, polygon_mm=poly)
            for i, poly in enumerate(polygons_mm)]
    rooms, oversized = _drop_oversized_rooms(rooms, area_label_points)
    for i, r in enumerate(rooms):
        r.index = i
    shapely_rooms = [Polygon(r.polygon_mm) for r in rooms]

    # секция: центроид комнаты по одну или другую сторону границы осей
    # «…с1»/«…с2» (см. _axis_boundary_x) — считается один раз на лист, в
    # тех же сырых координатах (pt), что и сами подписи осей. Комнату с
    # УЖЕ проставленной секцией (парковка, `_drop_oversized_rooms`) не
    # трогаем — у неё своя, не по границе С01/С02.
    boundary_pt = _axis_boundary_x(words)
    if boundary_pt is not None:
        boundary_mm = boundary_pt * PT_TO_MM * scale - shift_x
        for room, poly in zip(rooms, shapely_rooms):
            if room.section is not None:
                continue
            cx = poly.centroid.x
            room.section = "С01" if cx < boundary_mm else "С02"

    # площадь: число вида «14,3» рядом со словом «м2», центр — в комнате
    matched_area = 0
    for i, w in enumerate(words):
        if not _AREA_RE.match(w[4]):
            continue
        nxt = words[i + 1] if i + 1 < len(words) else None
        if not nxt or "м2" not in nxt[4].replace("²", "2"):
            continue
        px, py = to_mm(w[0], w[1])
        point = Point(px, py)
        for room, poly in zip(rooms, shapely_rooms):
            if poly.contains(point):
                room.area_m2 = float(w[4].replace(",", "."))
                matched_area += 1
                break

    # врезки — каталог типов квартир, «ФРАГМЕНТ ПЛАНА» и т.п., тем же слоем
    # помещений, что и сам план (см. докстрока `_axis_envelope`) — вне
    # уверенного допуска сетки осей отбрасываются; в пограничной зоне
    # решает не расстояние, а связность с реальной геометрией листа
    # (`_perimeter_coverage`) — расстояние одно там не разводит настоящее
    # от постороннего (см. докстрока `_axis_envelope`).
    envelope = _axis_envelope(page)
    if envelope is not None:
        inside = [r for r in rooms if _within_envelope(r.polygon_mm, envelope)]
        outside = [r for r in rooms if not _within_envelope(r.polygon_mm, envelope)]
        dropped = []
        if outside:
            raw_walls = [w["polygon_mm"] for w in _wall_segments_raw(page, scale, shift_x, shift_y)]
            fragment_labels = _page_fragment_labels(page, scale, shift_x, shift_y)
            all_polys = [r.polygon_mm for r in rooms]
            for r in outside:
                # подпись «Фрагмент…» сильнее связности: у врезки бывают
                # свои (дублирующие) стены, покрытие периметра обманчиво.
                if _near_fragment_label(r.polygon_mm, fragment_labels):
                    dropped.append(r)
                    continue
                neighbors = [p for p in all_polys if p is not r.polygon_mm] + raw_walls
                if _perimeter_coverage(r.polygon_mm, neighbors) >= _WALL_COVERAGE_MIN:
                    inside.append(r)
                else:
                    dropped.append(r)
        rooms = inside
    else:
        dropped = []
    for i, r in enumerate(rooms):
        r.index = i  # переиндексация после отбрасывания — без разрывов

    warnings = []
    if rooms and matched_area < len(rooms) * 0.5:
        warnings.append(
            f"площадь найдена только у {matched_area} из {len(rooms)} "
            "помещений — проверьте разбор этого листа отдельно")
    if rooms and boundary_pt is None:
        warnings.append(
            "граница осей секций не определена (нет подписей «…с1»/«…с2» "
            "обеих секций сразу) — секция помещений этого листа не проставлена")
    if envelope is None:
        warnings.append(
            "на листе не нашлось ни одной подписи оси — врезки (каталог "
            "типов квартир, «Фрагмент плана» и т.п.), если они есть, не "
            "отфильтрованы")
    if dropped:
        площади = ", ".join(
            (f"{r.area_m2}" if r.area_m2 is not None else "без площади") for r in dropped)
        warnings.append(
            f"{len(dropped)} фигур(ы) слоя помещений отброшены как врезка "
            f"(каталог типов квартир, «Фрагмент плана» и т.п. — вне сетки "
            f"осей листа, не элементы схемы): {площади}")
    if oversized:
        warnings.append(
            f"{len(oversized)} фигур(ы) слоя помещений отброшены как фоновая "
            f"заливка на весь этаж (габарит почти во весь охват листа — не "
            f"отдельное помещение), не элементы схемы")
    return rooms, warnings


def parse_document(doc) -> tuple:
    """Разбор всего комплекта по FLOOR_PLANS. `doc` — уже открытый
    `fitz.Document` (см. `load()`). Возвращает (список Room, предупреждения)."""
    all_rooms = []
    warnings = []
    page_cache = {}
    for plan in FLOOR_PLANS:
        if plan.page not in page_cache:
            page = doc[plan.page - 1]
            try:
                rooms, page_warnings = parse_page(page)
                boundary_mm = _page_section_boundary_mm(page)
            except PdfRoomsError as e:
                warnings.append(f"Лист {plan.page} (этаж {plan.floor}): {e.message}")
                rooms, page_warnings, boundary_mm = [], [], None
            page_cache[plan.page] = (rooms, page_warnings, boundary_mm)
        rooms, page_warnings, boundary_mm = page_cache[plan.page]
        for w in page_warnings:
            warnings.append(f"Лист {plan.page} (этаж {plan.floor}): {w}")
        # Этаж с ОДНОЙ возможной секцией — она известна из таблицы этажей
        # надёжнее любой геометрии; определение по осям только для этажей,
        # общих для нескольких секций (иначе шум на границе листа мог бы
        # переспорить заведомо известный факт).
        known_section = plan.section_codes[0] if len(plan.section_codes) == 1 else None
        floor_rooms = rooms
        # Секция 1 на листах этажей выше 8-го показана «для информации»
        # (кровля/техчасть) — у ЭТОГО этажа её нет вовсе (замечено
        # пользователем 2026-08-27): всё левее границы осей секций
        # отбрасывается для единственно-секционных этажей целиком, не
        # просто переподписывается.
        if known_section == "С02" and boundary_mm is not None:
            def _cx(r):
                return sum(x for x, _ in r.polygon_mm) / len(r.polygon_mm)
            excluded = [r for r in floor_rooms if _cx(r) < boundary_mm]
            if excluded:
                warnings.append(
                    f"Лист {plan.page} (этаж {plan.floor}): {len(excluded)} "
                    "помещений(-ие) левее границы секций — секция 1 «для "
                    "информации» на этом листе, у этажа её нет, отброшены")
            floor_rooms = [r for r in floor_rooms if _cx(r) >= boundary_mm]
        for i, r in enumerate(floor_rooms):
            all_rooms.append(Room(floor=plan.floor, index=i,
                                  polygon_mm=r.polygon_mm, area_m2=r.area_m2,
                                  section=known_section or r.section,
                                  page=plan.page))
    return all_rooms, warnings


# Разметка машиномест лежит на том же слое, что монолитный бетон
# (`]]]_СТ_вн_Бетон`), и тоже заливкой — по слою/типу от настоящей стены
# не отличить (2026-08-31, прямое указание пользователя на разбор той же
# парковки: жёлтым — просто границы места, зелёным — настоящие
# несущие стены, других стен в зоне парковки нет). Разводит ЦВЕТ заливки:
# на всём листе подвала это ровно 74 фигуры, все — этот жёлтый и только
# на этом слое (проверено), у остальных материалов такого цвета нет нигде
# в комплекте — яркий жёлтый для железобетона/кирпича/газобетона не
# используется никем, это цвет разметки, а не материала.
_MARKING_FILL_COLOR = (0.925, 0.925, 0.0)
_MARKING_FILL_TOLERANCE = 0.02


def _is_marking_fill(fill) -> bool:
    if not fill:
        return False
    return all(abs(c - m) <= _MARKING_FILL_TOLERANCE
              for c, m in zip(fill, _MARKING_FILL_COLOR))


def _wall_segments_raw(page, scale: int, shift_x: float, shift_y: float) -> list:
    """Залитые прямоугольники слоёв материала стен (`_WALL_LAYERS`) на
    ВСЁМ листе — легенда материалов ещё не отсечена (см. `parse_walls_
    page`). Один прямоугольник — один ПРЯМОЙ участок стены: под
    штриховкой (тысячи мелких обрывков линий, `type == "s"`, о них
    докстрока модуля) лежит настоящая заливка (`type == "f"`) — по одной
    фигуре на прямой кусок стены между углами/проёмами, толщина —
    короткая сторона её прямоугольника. `shift_x`/`shift_y` — тот же сдвиг
    выравнивания, что и у `_room_polygons` (передаётся, а не считается
    заново — один и тот же для всех слоёв листа). Разметка машиномест
    (`_is_marking_fill`) исключается — не материал, а линия по месту."""
    H = page.rect.height
    out = []
    for d in page.get_cdrawings():
        spec = _WALL_LAYERS.get(d.get("layer"))
        if not spec or d["type"] != "f" or _is_marking_fill(d.get("fill")):
            continue
        pts = [it[1] for it in d["items"] if it[0] == "l"]
        if d["items"]:
            pts.append(d["items"][-1][2])
        if len(pts) < 3:
            continue
        rect = d["rect"]
        if (rect[2] - rect[0]) * (rect[3] - rect[1]) < 0.05:
            continue  # шум — точечные обрывки контура
        poly = [(x * PT_TO_MM * scale - shift_x, (H - y) * PT_TO_MM * scale - shift_y)
                for x, y in pts]
        category, material = spec
        thickness = round(min(rect[2] - rect[0], rect[3] - rect[1]) * PT_TO_MM * scale, 1)
        out.append({"category": category, "material": material,
                    "polygon_mm": poly, "thickness_mm": thickness})
    return out


# Слой фасадной штриховки — по умолчанию декоративный мусор (тысячи
# обрывков кирпичной/панельной текстуры), но у экструзионного стыка между
# двумя монолитными участками (на плане — прямоугольниками поперёк фасада)
# на нём же лежит НАСТОЯЩАЯ кладка простенка и переплёт окна между ними,
# без которых простенок остаётся дырой (2026-08-31, найдено по указанию
# пользователя на конкретном узле между осями 14с2/16с2, лист 13). Слой не
# добавлен в `_WALL_LAYERS` — фигуры там нельзя брать все подряд, нужен
# отдельный отбор, см. `_exterior_infill_segments`.
_EXTERIOR_FACADE_LAYER = "]]]_СТЕНЫ_наружные.]"
_EXTERIOR_INFILL_MATERIAL = ("Стены", "Ячеистый бетон (наружная кладка)")
# Минимальный габарит фигуры, чтобы считаться настоящим блоком кладки, а
# не точечным обрывком декоративной штриховки (мелкие обрывки текстуры —
# порядка 80×80мм и меньше, реальные простенки в проверенном случае от
# 520×200мм).
_EXTERIOR_INFILL_MIN_AREA_MM2 = 30000
# Свой запас охвата, ШИРЕ общего `_AXIS_ENVELOPE_MARGIN_MM` (2026-08-31,
# найдено на стыке этажей 1-2, живой запрос пользователя): закруглённый
# угол здания геометрически выступает за прямоугольник сетки осей больше,
# чем толщина стены — общий запас (3000мм, откалиброван на прямых стенах)
# на проверенном случае не дотягивал 160-325мм, и кусок кладки на самом
# закруглении терялся молча. Не трогает общий запас `parse_page`
# (там — отбор врезок по слою помещений, другая задача и другие данные).
#
# ТОЛЬКО для листа 1 этажа (`_ROUNDED_CORNER_PAGE`) — закругление там
# ЕДИНСТВЕННОЕ на всё здание (2026-08-31, прямое уточнение пользователя:
# «полукруглый элемент... есть только на первом этаже»). Общий для всех
# листов запас 4000мм у другого листа (стр.6, этаж 2) уже цеплял ЧУЖОЕ —
# элемент фасада вне здания (центроид на 538мм дальше старого запаса
# 3000мм, но внутри нового) начинал просачиваться в модель как «кладка».
_EXTERIOR_INFILL_ENVELOPE_MARGIN_MM = 4000
_ROUNDED_CORNER_PAGE = 5
# Зазор для ПРОСТРАНСТВЕННОЙ кластеризации (см. докстрока функции) — на
# порядок больше типичного зазора между соседними импостами одного окна
# (десятки мм), но заведомо меньше расстояния между соседними окнами
# (простенок между ними — от 500мм).
_EXTERIOR_CLUSTER_GAP_MM = 400
# Сколько повторов размера в одном пространственном кластере считать
# окном (2026-08-31, живой найдено на этаже 1 — там повторов только 2, не
# 3+, окна не распознавались вовсе). При 2 растёт риск случайного
# совпадения размера у НЕ связанных фрагментов — ограничен размером
# итога, см. `_WINDOW_MAX_SPAN_MM`.
_WINDOW_MIN_REPEAT = 2
# Настоящее окно жилого дома — единицы метров max; проверенный ложный
# случай на пороге 2 — 15300мм (случайно совпавшая по размеру пара
# фрагментов кладки в разных концах фасада).
_WINDOW_MAX_SPAN_MM = 6000
_WINDOW_CATEGORY = ("Окна", "Окно (типовое, по узору переплёта)")
# Высота и отступ окна от отметки этажа — ПРИБЛИЖЕНИЕ, не измерение: в
# плане (вид сверху) вертикальная привязка не нарисована вовсе, взять её
# неоткуда. Значения — типовой подоконник/высота окна жилого дома.
_WINDOW_SILL_MM = 900
_WINDOW_HEIGHT_MM = 1500


def _exterior_infill_segments(page, scale: int, shift_x: float, shift_y: float,
                              envelope, margin: int = _AXIS_ENVELOPE_MARGIN_MM) -> tuple:
    """Кладка простенков наружного фасада И оконные проёмы между ними
    (`_EXTERIOR_FACADE_LAYER`) — на одном слое, одним способом (заливка,
    не штриховка), различить по слою/цвету нельзя — оба белые. Надёжный
    признак — окно всегда собрано из НЕСКОЛЬКИХ одинаковых по размеру
    повторяющихся фигур (переплёт/импосты), кладка — из фигур РАЗНОГО
    размера (нерегулярные куски простенка).

    Прежде чем сравнивать размеры, фигуры делятся на ПРОСТРАНСТВЕННЫЕ
    кластеры (`_EXTERIOR_CLUSTER_GAP_MM`) — иначе два РАЗНЫХ окна одного
    типоразмера в разных местах фасада слились бы в один прямоугольник
    через всю стену между ними. Внутри кластера фигура, совпадающая по
    (ширине, высоте) ещё с двумя и более в пределах 10мм, — окно; иначе —
    кладка.

    Ограничено сеткой осей листа (`envelope`, см. `_axis_envelope`) — тот
    же слой несёт фасадную штриховку по всему листу, не только у стен.
    Запас по умолчанию — общий `_AXIS_ENVELOPE_MARGIN_MM`; листу
    закруглённого угла (`_ROUNDED_CORNER_PAGE`) вызывающий код передаёт
    более широкий `_EXTERIOR_INFILL_ENVELOPE_MARGIN_MM` — см. её докстроку,
    почему НЕ общий для всех листов. Возвращает (кладка, окна) — оба
    списка словарей вида `_wall_segments_raw`, окна дополнительно несут
    `z_offset_mm`/`z_height_mm` (`_WINDOW_SILL_MM`/`_WINDOW_HEIGHT_MM`)."""
    if envelope is None:
        return [], []
    x0, x1, y0, y1 = envelope
    m = margin
    H = page.rect.height
    candidates = []
    for d in page.get_cdrawings():
        if d.get("layer") != _EXTERIOR_FACADE_LAYER or d["type"] != "f":
            continue
        fill = d.get("fill")
        if not fill or sum(fill[:3]) < 2.9:   # только белые фигуры (кладка/окно) — серые (вентфасад) не наш случай
            continue
        rect = d["rect"]
        w_mm = (rect[2] - rect[0]) * PT_TO_MM * scale
        h_mm = (rect[3] - rect[1]) * PT_TO_MM * scale
        if w_mm * h_mm < _EXTERIOR_INFILL_MIN_AREA_MM2:
            continue
        pts = [it[1] for it in d["items"] if it[0] == "l"]
        if d["items"]:
            pts.append(d["items"][-1][2])
        if len(pts) < 3:
            continue
        poly = [(x * PT_TO_MM * scale - shift_x, (H - y) * PT_TO_MM * scale - shift_y)
                for x, y in pts]
        cx, cy = _seg_centroid(poly)
        if not (x0 - m <= cx <= x1 + m and y0 - m <= cy <= y1 + m):
            continue
        candidates.append({"poly": poly, "w": w_mm, "h": h_mm})
    if not candidates:
        return [], []

    # Кластеризовать все фигуры сразу (по проксимити) НЕЛЬЗЯ: кладка идёт
    # сплошной цепочкой вдоль всего фасада, поэтому buffer+union по всем
    # фигурам склеивает периметр этажа в один кластер, а не по окнам —
    # окно тогда получалось растянутым через весь этаж. Сначала группируем
    # по РАЗМЕРУ (одинаковый переплёт), и только одинаковые по размеру
    # фигуры кластеризуем пространственно — так простенок между двумя
    # разными окнами одного типоразмера их не склеивает.
    wall_category, wall_material = _EXTERIOR_INFILL_MATERIAL
    win_category, win_material = _WINDOW_CATEGORY
    walls_out, windows_out = [], []
    by_size = {}
    for c in candidates:
        size = (round(c["w"] / 10) * 10, round(c["h"] / 10) * 10)
        by_size.setdefault(size, []).append(c)

    claimed = set()
    for members in by_size.values():
        if len(members) < _WINDOW_MIN_REPEAT:
            continue
        # buffer(GAP/2) на каждую фигуру — слипаются те, у кого реальный
        # зазор МЕНЬШЕ GAP (не 2×GAP, как было бы при buffer(GAP)).
        shapes = [Polygon(c["poly"]).buffer(_EXTERIOR_CLUSTER_GAP_MM / 2) for c in members]
        merged = unary_union(shapes)
        pieces = list(merged.geoms) if merged.geom_type == "MultiPolygon" else [merged]
        for piece in pieces:
            group = [c for c in members if piece.contains(Polygon(c["poly"]).centroid)]
            if len(group) < _WINDOW_MIN_REPEAT:
                continue
            xs = [x for c in group for x, _ in c["poly"]]
            ys = [y for c in group for _, y in c["poly"]]
            # Порог повтора снижен до 2 (2026-08-31, живой найдено на
            # этаже 1 — там у окна только 2 повторяющихся импоста, не 3+,
            # и окна не распознавались вовсе). При 2 случайная пара
            # похожих по размеру, но НЕ связанных фрагментов кладки
            # изредка проходит порог — отсекаем размером: настоящее окно
            # не бывает шире `_WINDOW_MAX_SPAN_MM` (проверенный ложный
            # случай — 15300мм, реальные окна — единицы метров).
            if max(max(xs) - min(xs), max(ys) - min(ys)) > _WINDOW_MAX_SPAN_MM:
                continue
            windows_out.append({
                "category": win_category, "material": win_material,
                "polygon_mm": [(min(xs), min(ys)), (max(xs), min(ys)),
                              (max(xs), max(ys)), (min(xs), max(ys))],
                "thickness_mm": round(min(max(xs) - min(xs), max(ys) - min(ys)), 1),
                "z_offset_mm": _WINDOW_SILL_MM, "z_height_mm": _WINDOW_HEIGHT_MM,
            })
            claimed.update(id(c) for c in group)

    for c in candidates:
        if id(c) in claimed:
            continue
        walls_out.append({"category": wall_category, "material": wall_material,
                          "polygon_mm": c["poly"],
                          "thickness_mm": round(min(c["w"], c["h"]), 1)})
    return walls_out, _merge_overlapping_windows(windows_out)


def _merge_overlapping_windows(windows: list) -> list:
    """Один физический проём часто даёт ДВА типоразмера повторяющихся
    фигур (рама и створка/импосты внутри неё) — каждый проходит отбор
    `_exterior_infill_segments` независимо и превращается в свой прямо-
    угольник почти в одном месте. Здесь такие пересекающиеся прямоугольники
    сливаются в один — по объединению их габаритов."""
    if not windows:
        return windows
    boxes = [box(*Polygon(w["polygon_mm"]).bounds) for w in windows]
    merged = unary_union(boxes)
    pieces = list(merged.geoms) if merged.geom_type == "MultiPolygon" else [merged]
    out = []
    for piece in pieces:
        group = [w for w, b in zip(windows, boxes) if piece.intersects(b.centroid)]
        if not group:
            continue
        xs = [x for w in group for x, _ in w["polygon_mm"]]
        ys = [y for w in group for _, y in w["polygon_mm"]]
        base = group[0]
        out.append({
            **base,
            "polygon_mm": [(min(xs), min(ys)), (max(xs), min(ys)),
                          (max(xs), max(ys)), (min(xs), max(ys))],
            "thickness_mm": round(min(max(xs) - min(xs), max(ys) - min(ys)), 1),
        })
    return out


def _seg_centroid(poly) -> tuple:
    n = len(poly)
    return (sum(p[0] for p in poly) / n, sum(p[1] for p in poly) / n)


def parse_walls_page(page, rooms: list = None) -> tuple:
    """Стены и перегородки листа, за вычетом легенды материалов, плюс их
    секция (по той же границе подписей осей, что и у помещений — см.
    `_axis_boundary_x`). Возвращает (список словарей, предупреждения).

    `rooms` — пары (контур, секция) помещений ЭТОГО листа, УЖЕ БЕЗ врезок
    (`_axis_envelope`, тот же список, что для соответствующего
    этажа вернул `parse_document`) — иначе врезка («ФРАГМЕНТ ПЛАНА» и
    т.п.) раздувает отступ легенды (`_LEGEND_MARGIN_MM`) до себя самой,
    и дублирующие стены/перегородки этой врезки просачиваются в модель
    точно так же, как просачивались бы дублирующие помещения. Секция
    помещения используется и для СВОИХ стен — каждая берёт секцию
    БЛИЖАЙШЕГО помещения листа (см. ниже) — при `None` считается заново
    по слою помещений без разбора врезок и без секций: годится для
    автономного вызова, не для `parse_walls_document`."""
    scale = _page_scale(page)
    raw_polys, (shift_x, shift_y) = _room_polygons(page, scale)
    if rooms is None:
        rooms = [(p, None) for p in raw_polys]
    room_polys = [p for p, _ in rooms]
    segments = _wall_segments_raw(page, scale, shift_x, shift_y)
    warnings = []
    if not room_polys:
        return [], warnings

    xs = [x for poly in room_polys for x, _ in poly]
    ys = [y for poly in room_polys for _, y in poly]
    x0, x1 = min(xs) - _LEGEND_MARGIN_MM, max(xs) + _LEGEND_MARGIN_MM
    y0, y1 = min(ys) - _LEGEND_MARGIN_MM, max(ys) + _LEGEND_MARGIN_MM
    segments = [s for s in segments
               if x0 <= _seg_centroid(s["polygon_mm"])[0] <= x1
               and y0 <= _seg_centroid(s["polygon_mm"])[1] <= y1]
    infill_margin = (_EXTERIOR_INFILL_ENVELOPE_MARGIN_MM
                     if page.number + 1 == _ROUNDED_CORNER_PAGE
                     else _AXIS_ENVELOPE_MARGIN_MM)
    infill_walls, infill_windows = _exterior_infill_segments(
        page, scale, shift_x, shift_y, _axis_envelope(page), infill_margin)
    segments += infill_walls
    segments += infill_windows

    words = page.get_text("words")
    boundary_pt = _axis_boundary_x(words)
    if boundary_pt is not None:
        boundary_mm = boundary_pt * PT_TO_MM * scale - shift_x
        # Одно большое помещение (открытая парковка без перегородок между
        # секциями — «один блок без деления», найдено пользователем по
        # исходному чертежу) может физически перекрывать границу осей
        # «…с1»/«…с2»: у самого помещения это не проблема (`parse_page`
        # решает по центроиду ВСЕЙ комнаты, не режет её), а вот её же
        # стены/колонны — каждая по СВОЕМУ центроиду — раскладывались бы
        # по разным секциям вперемешку друг с другом, хотя комната внутри
        # уже одна. Секция стены поэтому берётся у БЛИЖАЙШЕГО помещения
        # листа — но только если оно действительно РЯДОМ
        # (`_NEAREST_ROOM_MAX_MM`, проверено на реальных стенах парковки —
        # максимум 2,4м, порог с большим запасом): без предела приём
        # ломался в другую сторону (2026-08-31, найдено пользователем на
        # этаже 9) — проекция нижних этажей «для наглядности» на
        # односекционном этаже (в 30 МЕТРАХ от реальных помещений) не
        # имеет своей секции по границе, ближайшим для неё оказывалось
        # первое попавшееся помещение С02, и «секция 1 для информации»
        # (ниже) переставала её отсеивать — рамка нижних этажей
        # просачивалась в модель. Далеко от любого помещения — граница
        # остаётся резервом, как и при пустом списке помещений (автономный
        # вызов, `rooms=None`).
        near_rooms = [(Polygon(p), sec) for p, sec in rooms if sec and len(p) >= 3]
        for s in segments:
            cx, cy = _seg_centroid(s["polygon_mm"])
            nearest = None
            if near_rooms:
                point = Point(cx, cy)
                nearest = min(
                    ((poly.distance(point), sec) for poly, sec in near_rooms),
                    key=lambda t: t[0])
            if nearest is not None and nearest[0] <= _NEAREST_ROOM_MAX_MM:
                s["section"] = nearest[1]
            else:
                s["section"] = "С01" if cx < boundary_mm else "С02"
    else:
        for s in segments:
            s["section"] = None

    segments.sort(key=lambda s: (-round(_seg_centroid(s["polygon_mm"])[1]),
                                 round(_seg_centroid(s["polygon_mm"])[0])))
    return segments, warnings


def _floor_slab_polygon(room_polys: list, wall_polys: list) -> Optional[list]:
    """Контур плиты перекрытия — приближение объединением контуров
    помещений и стен этажа (см. докстрока `Slab`), а не измерение.
    Внутренние отверстия объединения (шахты, колодцы) отбрасываются —
    это контур ЗДАНИЯ, а не точная форма плиты со всеми вырезами."""
    shapes = []
    for poly in room_polys + wall_polys:
        if len(poly) < 3:
            continue
        try:
            shp = Polygon(poly).buffer(0)
        except Exception:
            continue
        if shp and not shp.is_empty:
            shapes.append(shp)
    if not shapes:
        return None
    merged = unary_union(shapes)
    if merged.is_empty:
        return None
    if merged.geom_type == "MultiPolygon":
        merged = max(merged.geoms, key=lambda g: g.area)
    if merged.geom_type != "Polygon":
        return None
    return [(round(x, 1), round(y, 1)) for x, y in merged.exterior.coords[:-1]]


def parse_walls_document(doc, rooms: list) -> tuple:
    """Стены, перегородки и плиты перекрытия по тем же листам, что и
    `parse_document`. `rooms` — уже разобранные помещения (тот же вызов) —
    их контуры участвуют в приближении плиты и не разбираются заново.

    Возвращает (список WallSegment, список Slab, предупреждения)."""
    rooms_by_floor = {}
    for r in rooms:
        rooms_by_floor.setdefault(r.floor, []).append((r.polygon_mm, r.section))

    all_walls = []
    all_slabs = []
    warnings = []
    page_cache = {}
    for plan in FLOOR_PLANS:
        if plan.page not in page_cache:
            page = doc[plan.page - 1]
            try:
                page_cache[plan.page] = parse_walls_page(
                    page, rooms_by_floor.get(plan.floor) or [])
            except PdfRoomsError as e:
                warnings.append(f"Лист {plan.page} (этаж {plan.floor}): {e.message}")
                page_cache[plan.page] = ([], [])
        segments, page_warnings = page_cache[plan.page]
        for w in page_warnings:
            warnings.append(f"Лист {plan.page} (этаж {plan.floor}): {w}")

        known_section = plan.section_codes[0] if len(plan.section_codes) == 1 else None
        floor_segments = segments
        # Секция 1 на листах этажей выше 8-го — «для информации», у этого
        # этажа её нет (тот же случай, что и у помещений, `parse_document`):
        # стены/перегородки левее границы осей секций отбрасываются
        # целиком для единственно-секционных этажей.
        if known_section == "С02":
            excluded = [s for s in floor_segments if s.get("section") == "С01"]
            if excluded:
                warnings.append(
                    f"Лист {plan.page} (этаж {plan.floor}): {len(excluded)} "
                    "стен(-ы)/перегородок левее границы секций — секция 1 "
                    "«для информации» на этом листе, у этажа её нет, отброшены")
            floor_segments = [s for s in floor_segments if s.get("section") != "С01"]
        for i, s in enumerate(floor_segments):
            all_walls.append(WallSegment(
                floor=plan.floor, index=i, page=plan.page,
                category=s["category"], material=s["material"],
                polygon_mm=s["polygon_mm"], thickness_mm=s["thickness_mm"],
                section=known_section or s.get("section"),
                z_offset_mm=s.get("z_offset_mm"), z_height_mm=s.get("z_height_mm")))

        room_polys = [p for p, _ in (rooms_by_floor.get(plan.floor) or [])]
        slab_poly = _floor_slab_polygon(room_polys, [s["polygon_mm"] for s in floor_segments])
        if slab_poly:
            all_slabs.append(Slab(floor=plan.floor, polygon_mm=slab_poly, page=plan.page))
        elif room_polys:
            warnings.append(f"Лист {plan.page} (этаж {plan.floor}): "
                           "не удалось приблизить контур плиты перекрытия")
    return all_walls, all_slabs, warnings


def page_axis_labels(page) -> dict:
    """Подписи осей листа — основных (`_AXIS_RE`, «Ас1») и вспомогательных
    (`_AXIS_AUX_RE`, «Аа», без номера секции) — в тех же выровненных мм-
    координатах, что и контуры помещений (`_room_polygons` — тот же сдвиг,
    независимо посчитанный для этого листа). Возвращает `{подпись:
    (направление, координата)}`: направление `'x'` — вертикальная ось
    (подпись цифрой, «1», «15» — стандартное черчение нумерует ими
    вертикальные оси), `'y'` — горизонтальная (подпись буквой, «А», «Б»).
    Несколько вхождений одной подписи на листе — координата усредняется.

    Потребителю, которому нужны СТРОГО основные оси с номером секции
    (`app/pdf_import._apply_axis_grid` — привязка секции к осям), это не
    мешает: он сам заново проверяет подпись через `_AXIS_RE` и молча
    пропускает вспомогательные — они у него не участвуют."""
    scale = _page_scale(page)
    _, (shift_x, shift_y) = _room_polygons(page, scale)
    H = page.rect.height
    buckets = {}
    for w in page.get_text("words"):
        m = _AXIS_RE.match(w[4]) or _AXIS_AUX_RE.match(w[4])
        if not m:
            continue
        label = w[4]
        направление = "x" if m.group(1).isdigit() else "y"
        x_mm = w[0] * PT_TO_MM * scale - shift_x
        y_mm = (H - w[1]) * PT_TO_MM * scale - shift_y
        координата = x_mm if направление == "x" else y_mm
        buckets.setdefault(label, (направление, []))[1].append(координата)
    return {label: (направление, sum(coords) / len(coords))
            for label, (направление, coords) in buckets.items()}


def extract_axis_grid(doc) -> dict:
    """Подписи осей обеих секций сразу — с одного листа общего этажа
    (`RoomPlan.section_codes` из двух кодов, см. `_SPEC`): только там
    заведомо показаны оси и секции 1, и секции 2 (та же логика, что у
    `_axis_boundary_x`). `{}`, если такого листа в комплекте нет.

    Лист выбирается не первым попавшимся, а ТИПОВЫМ по сдвигу
    (`_room_polygons` выравнивает каждый лист по своему верхнему правому
    углу застройки, см. её докстроку) — 2026-08-31, найдено пользователем
    по нестыковке сетки осей с реальными стенами на верхних этажах.
    Подземный этаж и 1-2 этажи шире/уже типовой башни (парковка,
    вестибюль) и потому выравниваются на ДРУГУЮ точку — их сдвиг не
    совпадает с большинством листов (проверено: 90469±0 мм у семи листов
    из девяти, у подземного 111619, у 1 этажа 108799, у 2 этажа 96088).
    `object_grids` — ОДНА сетка на весь объект (те же самые физические
    оси на любом этаже), поэтому важно взять её с листа, чей сдвиг
    совпадает с большинством, а не с первого попавшегося, где есть обе
    секции сразу."""
    shared_pages = [p for p in FLOOR_PLANS if len(p.section_codes) == 2]
    if not shared_pages:
        return {}
    shifts = {}
    for page_no in sorted({p.page for p in FLOOR_PLANS}):
        page = doc[page_no - 1]
        _, shift = _room_polygons(page, _page_scale(page))
        shifts[page_no] = (round(shift[0]), round(shift[1]))
    counts = {}
    for s in shifts.values():
        counts[s] = counts.get(s, 0) + 1
    типовой_сдвиг = max(counts.items(), key=lambda kv: kv[1])[0]
    typical_pages = {page_no for page_no, s in shifts.items() if s == типовой_сдвиг}
    shared_pages.sort(key=lambda p: (p.page not in typical_pages, p.page))
    return page_axis_labels(doc[shared_pages[0].page - 1])


