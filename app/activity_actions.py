ACTION_TITLES = {code: title for code, (title, _) in ACTIONS.items()}
ACTION_CATEGORIES = {code: category for code, (_, category) in ACTIONS.items()}


def action_title(action: str) -> str:
    """Подпись действия; неизвестный код показывается как есть — лучше
    голый код, чем пустая ячейка."""
    return ACTION_TITLES.get(action, action)


def category_of(action: str) -> str:
    """Категория действия. Неизвестный код — «Прочее»: журнал обязан
    записать событие в любом случае, даже если подпись ему забыли завести
    (страж поймает это раньше, в pre-commit)."""
    return ACTION_CATEGORIES.get(action, CATEGORY_OTHER)


def category_title(category: str) -> str:
    return CATEGORY_TITLES.get(category, category or "")
