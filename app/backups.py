#
# Пять — «последние пять служебных», а не пять на каждый вид: так решил
# пользователь. Считается по всему множеству служебных сразу, то есть это
# примерно два с половиной последних релиза.
KEEP_SERVICE_BACKUPS = 5

# ---------------------------------------------------- свободное место
#
# Зачем контроль (запрос пользователя 2026-08-19). Копия базы снимается САМА
# перед каждым потенциально разрушительным действием и, главное, перед первым
# стартом новой версии — ДО миграций и обработок, первой же строкой
# `on_startup`. Кончившееся место означает не «копия не снялась», а
# НЕПОДНЯВШИЙСЯ СЕРВИС: исключение уходит наверх из обработчика старта, и
# контейнер уходит в цикл перезапуска. Место — единственный расходуемый
# ресурс, который copy-on-write не прощает, и узнать о нём надо ДО того, как
# он кончился, а не по нерабочему сервису.
#
# Порог мерится В КОПИЯХ БАЗЫ, а не в процентах диска, — потому что ломается
# ровно «снять ещё одну копию». Процент от тома отвечал бы на другой вопрос и
# на большом диске врал бы в обе стороны.
#
# Абсолютный пол — рядом с ним, потому что на том же томе живут вложения,
# чертежи, образы Docker и журналы: база может быть крошечной, а место
# кончиться из-за соседей. Пол выбран так, чтобы предупреждение приходило
# заметно раньше отказа, а не вместе с ним.
DISK_CRITICAL_COPIES = 2          # меньше — следующая копия может не поместиться
DISK_WARNING_COPIES = 5           # меньше — пора убирать, но ещё работает
DISK_CRITICAL_FLOOR = 1 * 1024 ** 3   # 1 ГБ
DISK_WARNING_FLOOR = 3 * 1024 ** 3    # 3 ГБ

DISK_OK = "ok"
DISK_WARNING = "warning"
DISK_CRITICAL = "critical"


def database_bytes() -> int:
    """Размер базы вместе со спутниками `-wal`/`-shm`: копия снимается со
    ВСЕГО состояния, и место нужно под него целиком."""
    итог = 0
    for суффикс in ("", "-wal", "-shm"):
        путь = Path(str(_db.DB_PATH) + суффикс)
        if путь.exists():
            итог += путь.stat().st_size
    return итог


def disk_state() -> dict:
    """Сколько места осталось там, где лежат база и копии, и насколько это
    мало. Готово к показу: `message` — человеческий текст или None.

    Меряется том, на котором лежит ПАПКА КОПИЙ: база и копии в этой схеме
    развёртывания на одном томе (`/opt/zhbi/data` смонтирована целиком), а
    если кто-то разнесёт их по разным, кончится место именно под копии — за
    ним и следим.

    Ошибку `shutil.disk_usage` глушим намеренно: контроль места не должен
    ронять ни экран копий, ни старт сервиса. Не смогли узнать — говорим, что
    не смогли, и не мешаем работать.
    """
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    try:
        всего, занято, свободно = shutil.disk_usage(BACKUP_DIR)
    except OSError as exc:
        return {"known": False, "level": DISK_OK, "message": None,
                "error": f"не удалось узнать свободное место: {exc}"}
    база = database_bytes()
    копий_влезет = int(свободно // база) if база else None

    # Причина называется явно, а не выводится из чисел читателем. Порогов
    # два, и они срабатывают в разных случаях: у крупной базы первым
    # упирается счёт копий, у маленькой — абсолютный пол (место съели
    # вложения, чертежи, образы Docker). Сообщение «мало места, хватит на
    # 262144 копии» — то самое, что заставляет не доверять предупреждениям.
    мало_под_копии = bool(база) and свободно < база * DISK_WARNING_COPIES
    почти_нет_под_копии = bool(база) and свободно < база * DISK_CRITICAL_COPIES
    уровень = DISK_OK
    if свободно < DISK_CRITICAL_FLOOR or почти_нет_под_копии:
        уровень = DISK_CRITICAL
    elif свободно < DISK_WARNING_FLOOR or мало_под_копии:
        уровень = DISK_WARNING

    сообщение = причина = None
    if уровень != DISK_OK:
        по_копиям = почти_нет_под_копии if уровень == DISK_CRITICAL else мало_под_копии
        начало = ("Критически мало места на диске" if уровень == DISK_CRITICAL
                  else "Мало места на диске")
        причина = "копии" if по_копиям else "том"
        если_копии = (
            f"под копию базы ({_объём(база)}) его почти не осталось"
            if уровень == DISK_CRITICAL else
            f"этого хватит примерно на {_копий(копий_влезет)} базы по {_объём(база)}"
        )
        если_том = ("на этом же томе лежат вложения, чертежи и образы Docker, "
                    "место могли занять они")
        хвост = ("Копия базы снимается перед КАЖДЫМ обновлением, до миграций: "
                 "не хватит места — сервис не запустится."
                 if уровень == DISK_CRITICAL else
                 "Копия базы снимается перед каждым обновлением; когда места "
                 "перестанет хватать, сервис не запустится.")
        сообщение = (f"{начало}: свободно {_объём(свободно)} из {_объём(всего)} — "
                     f"{если_копии if по_копиям else если_том}. {хвост}")
    return {
        "known": True,
        "reason": причина,
        "total_bytes": всего,
        "used_bytes": занято,
        "free_bytes": свободно,
        "db_bytes": база,
        "copies_fit": копий_влезет,
        "level": уровень,
        "message": сообщение,
    }


def _копий(n: int) -> str:
    """«1 копию», «3 копии», «7 копий». Склонение здесь, а не «копий(и)» в
    тексте: сообщение читает человек в аварийной ситуации, и корявая фраза в
    нём стоит доверия ко всему предупреждению."""
    сотня, десяток = n % 100, n % 10
    if 11 <= сотня <= 14:
        форма = "копий"
    elif десяток == 1:
        форма = "копию"
    elif 2 <= десяток <= 4:
        форма = "копии"
    else:
        форма = "копий"
    return f"{n} {форма}"


def _объём(n: int) -> str:
    """Байты по-человечески: ГБ, МБ или КБ — по величине. Единица одна на всё
    сообщение не годится: «свободно 0.0 ГБ» при 700 МБ выглядит как поломка
    счётчика, а «база 37000.0 МБ» не читается."""
    if n >= 1024 ** 3:
        return f"{n / 1024 ** 3:.1f} ГБ"
    if n >= 1024 ** 2:
        return f"{n / 1024 ** 2:.0f} МБ"
    return f"{n / 1024:.0f} КБ"

