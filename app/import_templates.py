def _sample_dxf() -> bytes:
    """Минимальный, но НАСТОЯЩИЙ чертёж: 5 элементов пятью разными
    комбинациями тип/подтип/отметка, у каждого своя марка на парном слое
    «Марка», плюс зона захватки/крана/стоянки и сетка осей. Файл проходит
    обычный импорт, поэтому годится и как образец имён слоёв, и как
    проверочный файл на пустой установке.

    ezdxf импортируется внутри функции: модуль с описаниями шаблонов
    читается при каждом старте (его тянет app/main.py), а тяжёлый ezdxf
    нужен только в момент реальной генерации образца.
    """
    import ezdxf

    doc = ezdxf.new("R2010", setup=True)
    doc.header["$INSUNITS"] = 4  # миллиметры
    msp = doc.modelspace()

    # (Тип, Подтип, токен отметки, марка, левый нижний угол, размер) —
    # подтипы взяты из справочника подтипов по умолчанию, отметки
    # согласованы с подтипом-отметкой там, где он её дублирует.
    elements = [
        ("Колонна", "нижняя", "ОТМ00000", "1Кв1.1", (0, 0), (400, 400)),
        ("Колонна", "средняя нижний ярус", "ОТМП08050", "2Кв2.3", (6000, 0), (400, 400)),
        ("Ригель", "на отм. +15.000", "ОТМП15000", "3Р19.6", (400, 0), (5600, 400)),
        ("Ригель", "периметральный", "ОТМП05200", "1Р12.4", (400, 6000), (5600, 400)),
        ("Плита перекрытия", "на отм. +15.000", "ОТМП15000", "4П-1", (400, 400), (5600, 5600)),
    ]

    for element_type, subtype, elevation, mark, (x, y), (width, height) in elements:
        base = f"WEB_констр_{element_type}_{subtype}_{elevation}"
        element_layer, mark_layer = f"{base}_Элемент", f"{base}_Марка"
        for layer in (element_layer, mark_layer):
            if layer not in doc.layers:
                doc.layers.add(layer)
        msp.add_lwpolyline(
            [(x, y), (x + width, y), (x + width, y + height), (x, y + height)],
            close=True,
            dxfattribs={"layer": element_layer},
        )
        # Марка — текст внутри контура: так её находит разбор для случая
        # «на слое марок нет ни одной выноски» (см.
        # scripts/new_standard_pipeline.parse_new_standard_elements).
        msp.add_text(
            mark,
            height=200,
            dxfattribs={"layer": mark_layer},
        ).set_placement((x + width / 2, y + height / 2))

    zone_layers = {
        "WEB_тех_Захватка_Зона": [(-1000, -1000), (7500, -1000), (7500, 7500), (-1000, 7500)],
        "WEB_тех_Кран_Зона": [(-800, -800), (7300, -800), (7300, 7300), (-800, 7300)],
        "WEB_тех_Стоянки крана_ОТМ00000_Зона": [(-600, -600), (3200, -600), (3200, 7100), (-600, 7100)],
    }
    for layer, points in zone_layers.items():
        doc.layers.add(layer)
        msp.add_lwpolyline(points, close=True, dxfattribs={"layer": layer})

    zone_names = {
        "WEB_тех_Захватка_Наименование": ("Захватка 1", (3250, -900)),
        "WEB_тех_Кран_Наименование": ("Кран 1", (3250, -700)),
        "WEB_тех_Стоянки крана_ОТМ00000_Наименование": ("Стоянка 01", (1300, 3250)),
    }
    for layer, (text, point) in zone_names.items():
        doc.layers.add(layer)
        msp.add_text(text, height=200, dxfattribs={"layer": layer}).set_placement(point)

    # Сетка осей: блок с атрибутом метки — тот же вид, что читает
    # scripts/assign_axes (тег "А1").
    doc.layers.add("WEB_тех_Оси")
    block = doc.blocks.new(name="ОСЬ")
    block.add_circle((0, 0), radius=400)
    block.add_attdef(tag="А1", text="", dxfattribs={"height": 300, "invisible": 0})
    for label, (x, y) in [("1", (0, -2000)), ("2", (6000, -2000)), ("А", (-2000, 0)), ("Б", (-2000, 6000))]:
        ref = msp.add_blockref("ОСЬ", (x, y), dxfattribs={"layer": "WEB_тех_Оси"})
        ref.add_auto_attribs({"А1": label})

    stream = io.StringIO()
    doc.write(stream)
    return stream.getvalue().encode("utf-8")


