# --- Файлы-образцы -----------------------------------------------------------
#
# По 5 строк с РАЗНЫМИ корректными данными (требование пользователя): разные
# типы/подтипы, разные краны и этажи, разные статусы, разные поставщики — чтобы
# образец показывал не только формат ячейки, но и допустимый разброс значений.


def _xlsx_bytes(sheet_title: str, headers: list[str], rows: list[list]) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = sheet_title
    ws.append(headers)
    for row in rows:
        ws.append(row)
    for idx, header in enumerate(headers, start=1):
        width = max(len(str(header)), *(len(str(r[idx - 1])) for r in rows)) + 2
        ws.column_dimensions[ws.cell(row=1, column=idx).column_letter].width = min(width, 42)
    ws.freeze_panes = "A2"
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


