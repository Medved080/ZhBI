BLOCKS = (COMMON_BLOCKS + PLAN_BLOCKS + WORKSPACE_BLOCKS + ZONE_BLOCKS + CONTRACT_BLOCKS
          + REPORT_BLOCKS + DICT_BLOCKS + OBJECT_SETTINGS_BLOCKS + IMPORT_BLOCKS
          + SERVICE_BLOCKS + TRAINING_BLOCKS)

BLOCKS_BY_FEATURE = {b.feature: b for b in BLOCKS if b.feature}


def missing_features() -> list:
    """Разделы app/features.py, для которых учебного блока ещё нет.

    Отсюда работают и страж (scripts/check_training_coverage.py), и плашка
    на самом экране: материал пишется этапами, и «чего ещё нет» должно быть
    видно, а не подразумеваться.
    """
    return [f.key for f in FEATURES if f.key not in BLOCKS_BY_FEATURE]


def unknown_blocks() -> list:
    """Блоки, ссылающиеся на несуществующий раздел, — опечатка в ключе.

    Без этой проверки блок с опечаткой просто не показался бы никому и
    молча пропал бы вместе со своими вопросами.
    """
    известные = {f.key for f in FEATURES}
    return [b.key for b in BLOCKS if b.feature and b.feature not in известные]


# Секция общих блоков. Не из app/features.py: раздела прав у них нет — вход
# в систему и выбор объекта доступны всем, кто вообще вошёл.
COMMON_SECTION = "Начало работы"


def section_of(block: Block) -> str:
    """Секция блока — та же группировка, что у разделов прав. Оглавление
    инструкции и матрица прав так читаются одними глазами: человек, которому
    выдали «Контрактацию», найдёт её в инструкции под тем же заголовком."""
    if block.feature is None:
        return COMMON_SECTION
    return FEATURES_BY_KEY[block.feature].section


def blocks_for(levels: dict) -> list:
    """Инструкция под набор прав {ключ раздела: уровень}.

    Общие блоки — всегда. Блок раздела — если уровень не «нет». Абзацы
    уровня WRITE — только тем, у кого «Изменение»: они описывают кнопки,
    которых у читателя-наблюдателя нет, и инструкция к ним читалась бы как
    «мне это положено, но не работает».
    """
    итог = []
    for блок in BLOCKS:
        if блок.feature is None:
            уровень = WRITE
        else:
            уровень = levels.get(блок.feature) or "none"
            if уровень == "none":
                continue
        абзацы = [p for p in блок.paragraphs if p.level == READ or уровень == WRITE]
        if not абзацы:
            continue
        итог.append((блок, абзацы, уровень))
    return итог


def questions_for(levels: dict, feature: Optional[str] = None) -> list:
    """Все вопросы, уместные для набора прав. Выборку из них делает
    app/training.py — здесь только «что вообще можно спросить».

    `feature` сужает набор до ОДНОГО раздела: тест по разделу, который
    человек сейчас читает. Общие блоки в такой тест не подмешиваются — если
    спрашивают про контрактацию, вопрос про вход в систему выглядит
    ошибкой.
    """
    вопросы = []
    for блок, _абзацы, уровень in blocks_for(levels):
        if feature is not None and блок.feature != feature:
            continue
        for в in блок.questions:
            if в.level == WRITE and уровень != WRITE:
                continue
            вопросы.append((блок, в))
    return вопросы


def question(key: str):
    """Вопрос по ключу: нужен при проверке ответа. None — вопроса больше
    нет (материал правился между началом попытки и ответом)."""
    for блок in BLOCKS:
        for в in блок.questions:
            if в.key == key:
                return блок, в
    return None
