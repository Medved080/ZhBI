# -*- coding: utf-8 -*-
"""
Учебный материал: инструкция и вопросы теста (раздел «Обучение», 2026-08-14).

ГЛАВНОЕ РЕШЕНИЕ. Инструкции пишутся не «на роль», а **на раздел прав**
(app/features.py), и инструкция роли СОБИРАЕТСЯ из блоков тех разделов,
которые роли доступны. Иначе никак: с 2026-08-14 роли — данные, их заводит
и удаляет администратор в матрице (app/roles.py). Пять написанных руками
документов «для прораба», «для комплектовщика» разъехались бы с матрицей в
первый же рабочий день, а у заведённой завтра роли «Геодезист» инструкции
не было бы вовсе.

Отсюда все остальные свойства:

- у человека ролей несколько — его инструкция это ОБЪЕДИНЕНИЕ блоков по
  всем ролям, ровно как складываются сами права;
- абзац помечен уровнем: `READ` — «где посмотреть», `WRITE` — «как
  поменять». Тому, кому раздел дан на чтение, инструкция по правке не
  показывается: она описывает кнопки, которых у него нет;
- вопрос теста тоже помечен уровнем и задаётся только тому, кому адресован
  соответствующий абзац. Спрашивать «как отменить проведение документа» у
  того, кто документ только смотрит, — проверять чужую работу.

**Правило при добавлении раздела в app/features.py**: сюда же добавляется
блок. Иначе новая функциональность тихо выпадет из обучения — это ловит
`scripts/check_training_coverage.py` и плашка на самом экране. Тот же
приём, что у описаний полей БД (app/db_schema_doc.py): описание живёт
рядом с тем, что описывает, и молча устареть не может.

Материал лежит в КОДЕ, а не в базе: он приезжает с версией сервиса, правится
через ревью и переносится между серверами вместе с образом. `CONTENT_VERSION`
пишется в каждую попытку — по какой редакции человек сдавал, иначе история
прохождений начинает врать при первой же правке формулировок.

Вопросов на блок — два-три; в одну попытку из них берётся выборка (см.
app/training.py). Правильный ответ у вопроса ОДИН: множественный выбор
требует правил частичного зачёта, а разбор ответа после каждого вопроса
объясняет и без них.
"""

from typing import NamedTuple, Optional

