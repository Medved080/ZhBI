# Редакция материала. Меняется при ЛЮБОЙ правке текста или вопросов ниже:
# в истории прохождений она отвечает на вопрос «по какой редакции сдавали».
CONTENT_VERSION = "2026-08-22.4"


class Para(NamedTuple):
    """Абзац инструкции. `level` — кому он адресован: READ видят все, кому
    раздел доступен, WRITE — только те, кто может менять."""

    level: str
    text: str


class Question(NamedTuple):
    """Вопрос теста.

    `correct` — индекс правильного варианта в `options`. `explain` —
    разбор, который показывается СРАЗУ после ответа: почему верно и чем
    плохи остальные варианты. Разбор обязателен: тест здесь учит, а не
    аттестует, и вопрос без объяснения — просто отметка о незнании.
    """

    key: str
    level: str
    text: str
    options: list
    correct: int
    explain: str


class Block(NamedTuple):
    """Учебный блок. `feature` — ключ раздела app/features.py, к которому
    блок относится; None — общий блок, он в инструкции у всех."""

    key: str
    feature: Optional[str]
    title: str
    paragraphs: list
    questions: list


def _r(text: str) -> Para:
    return Para(READ, text)


def _w(text: str) -> Para:
    return Para(WRITE, text)


